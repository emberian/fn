#!/usr/bin/env python3
"""The repair ledger: one JSON file per item under planning/repair/items/.

One file per item so many agents can update different items without conflicts.
States: open -> in-progress -> ready -> landed  (or: refuted | duplicate | deferred).

  repair.py list [--owner LANE] [--state STATE] [--severity SEV] [--open]
  repair.py show ID
  repair.py set ID key=value [key=value ...]      e.g. state=ready sha=abc123 note="..."
  repair.py add ID title=... file=... severity=... owner=... source=... [key=value ...]
  repair.py report                               writes planning/repair/STATUS.md
  repair.py lanes                                prints lane -> agent id (for direct messages)
"""
import json, os, sys, time, glob, collections

ROOT = os.path.dirname(os.path.abspath(__file__))
ITEMS = os.path.join(ROOT, "items")
STATES = ["open", "in-progress", "ready", "landed", "refuted", "duplicate", "deferred"]
SEV = ["high", "medium", "low"]


def path(i):
    return os.path.join(ITEMS, f"{i}.json")


def load(i):
    with open(path(i)) as f:
        return json.load(f)


def save(d):
    d["updated"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime())
    tmp = path(d["id"]) + ".tmp"
    with open(tmp, "w") as f:
        json.dump(d, f, indent=1, sort_keys=True)
    os.replace(tmp, path(d["id"]))


def all_items():
    out = []
    for p in sorted(glob.glob(os.path.join(ITEMS, "*.json"))):
        with open(p) as f:
            out.append(json.load(f))
    return out


def kv(args):
    d = {}
    for a in args:
        k, _, v = a.partition("=")
        d[k] = v
    return d


def check(d):
    if d.get("state") and d["state"] not in STATES:
        sys.exit(f"bad state {d['state']}; one of {STATES}")
    if d.get("severity") and d["severity"] not in SEV:
        sys.exit(f"bad severity {d['severity']}; one of {SEV}")


def main(argv):
    if not argv:
        print(__doc__); return
    cmd, rest = argv[0], argv[1:]
    if cmd == "list":
        f = {}
        it = iter(rest)
        for a in it:
            if a == "--open":
                f["open"] = True
            else:
                f[a.lstrip("-")] = next(it)
        for d in all_items():
            if f.get("open") and d["state"] in ("landed", "refuted", "duplicate"):
                continue
            if any(k in d and d[k] != v for k, v in f.items() if k != "open"):
                continue
            print(f"{d['id']:10} {d['state']:11} {d.get('severity',''):6} {d.get('owner',''):20} {d.get('file','')}:{d.get('line','')}  {d['title'][:90]}")
    elif cmd == "show":
        print(json.dumps(load(rest[0]), indent=1, sort_keys=True))
    elif cmd == "set":
        d = load(rest[0]); upd = kv(rest[1:]); check(upd)
        if "note" in upd:
            d.setdefault("notes", []).append(time.strftime("%m-%d %H:%M ") + upd.pop("note"))
        d.update(upd); save(d); print(f"{d['id']} -> {d['state']}")
    elif cmd == "add":
        i = rest[0]
        if os.path.exists(path(i)):
            sys.exit(f"{i} exists")
        d = {"id": i, "state": "open", "notes": []}; d.update(kv(rest[1:])); check(d); save(d); print(f"added {i}")
    elif cmd == "report":
        items = all_items()
        by_state = collections.Counter(d["state"] for d in items)
        open_ = [d for d in items if d["state"] in ("open", "in-progress", "ready")]
        sev = collections.Counter(d.get("severity", "?") for d in open_)
        own = collections.defaultdict(collections.Counter)
        for d in items:
            own[d.get("owner", "?")][d["state"]] += 1
        lines = ["# Repair ledger status (generated by repair.py report)", "",
                 f"Generated {time.strftime('%Y-%m-%d %H:%M UTC', time.gmtime())}. Items: {len(items)}.", "",
                 "| state | count |", "|---|---|"]
        lines += [f"| {s} | {by_state.get(s,0)} |" for s in STATES]
        lines += ["", "Open (open + in-progress + ready) by severity: " + ", ".join(f"{s} {sev.get(s,0)}" for s in SEV), "",
                  "| owner | open | in-progress | ready | landed | other |", "|---|---|---|---|---|---|"]
        for o in sorted(own):
            c = own[o]
            other = sum(v for k, v in c.items() if k not in ("open", "in-progress", "ready", "landed"))
            lines.append(f"| {o} | {c['open']} | {c['in-progress']} | {c['ready']} | {c['landed']} | {other} |")
        lines += ["", "## Open high-severity items", ""]
        for d in sorted(open_, key=lambda d: d["id"]):
            if d.get("severity") == "high":
                lines.append(f"- {d['id']} [{d['state']}] {d.get('owner','?')}: {d['title']} ({d.get('file','')}:{d.get('line','')})")
        with open(os.path.join(ROOT, "STATUS.md"), "w") as f:
            f.write("\n".join(lines) + "\n")
        print("\n".join(lines[:16]))
    elif cmd == "lanes":
        p = os.path.join(ROOT, "lanes.json")  # local, untracked: lane -> agent id for the current swarm
        print(open(p).read() if os.path.exists(p) else "no lanes.json (it is local to a coordinator session)")
    else:
        print(__doc__)


if __name__ == "__main__":
    main(sys.argv[1:])
