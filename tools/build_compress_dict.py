#!/usr/bin/env python3
"""Build fn's baseline DEFLATE preset dictionary from text fn owns.

The recipe (docs/extensions/nntp-compress-dict.md, "The baseline
dictionary"): deterministic, no trained model, no third-party corpus.

  1. The inputs, in this order: the RFC texts in the repository root
     (rfc*.txt, sorted), docs/**/*.md, docs/articles/*.txt and specs/*.md
     (each sorted by path), every file's line ends made CRLF (the wire
     form).  `inputs` lists them with their SHA-256; the dictionary's
     manifest pins that list.
  2. Count every 8-octet substring (d-gram) of the concatenation.
  3. Cut every file into 64-octet segments at 64-octet offsets.  A
     segment's score is the sum of the counts of the distinct d-grams it
     holds that no chosen segment holds yet.
  4. Choose the best segment (score, then earlier file, then earlier
     offset), mark its d-grams used, and repeat until 32,768 octets are
     chosen (lazy re-scoring: a popped segment is re-scored and pushed back
     unless its score did not drop).
  5. Lay the chosen segments out in ascending score, so the most valuable
     text sits at the end of the dictionary, nearest the payload (DEFLATE's
     distance to it is shortest).

Outputs (under OUT): baseline.bin (the 32,768 octets), baseline.json (the
manifest: inputs and their digests, parameters, the dictionary's SHA-256
and BLAKE3 digests, its DICT-ID = the first four BLAKE3 octets, big-endian)
and, with --lisp PATH, the ACL2 table book's constant.

  python3 tools/build_compress_dict.py OUT [--lisp books/compress-dict-baseline.lisp]
  python3 tools/build_compress_dict.py --measure GATE.bin DICT.bin   # ratio on a gate file
"""
from __future__ import annotations

import glob
import hashlib
import heapq
import json
import os
import struct
import sys
import zlib

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import blake3_ref  # noqa: E402

SIZE = 32768
SEG = 64
D = 8


def inputs(root):
    names = sorted(glob.glob(os.path.join(root, "rfc*.txt")))
    names += sorted(glob.glob(os.path.join(root, "docs", "**", "*.md"), recursive=True))
    names += sorted(glob.glob(os.path.join(root, "docs", "articles", "*.txt")))
    names += sorted(glob.glob(os.path.join(root, "specs", "*.md")))
    out = []
    for n in names:
        b = open(n, "rb").read().replace(b"\r\n", b"\n").replace(b"\n", b"\r\n")
        out.append((os.path.relpath(n, root), b))
    return out


def build(files):
    counts = {}
    for _, b in files:
        for i in range(len(b) - D + 1):
            g = b[i:i + D]
            counts[g] = counts.get(g, 0) + 1
    segs = []
    for fi, (_, b) in enumerate(files):
        for off in range(0, len(b) - SEG + 1, SEG):
            segs.append((fi, off, b[off:off + SEG]))
    used = set()

    def score(seg):
        grams = {seg[i:i + D] for i in range(SEG - D + 1)}
        return sum(counts[g] for g in grams if g not in used)

    heap = [(-score(s), fi, off, s) for fi, off, s in segs]
    heapq.heapify(heap)
    chosen = []
    while heap and len(chosen) * SEG < SIZE:
        neg, fi, off, s = heapq.heappop(heap)
        now = score(s)
        if now < -neg:
            heapq.heappush(heap, (-now, fi, off, s))
            continue
        if now == 0:
            break
        chosen.append((now, fi, off, s))
        used.update(s[i:i + D] for i in range(SEG - D + 1))
    chosen.sort(key=lambda c: (c[0], -c[1], -c[2]))
    return b"".join(c[3] for c in chosen)[-SIZE:]


def manifest(root, files, d):
    b3 = blake3_ref.blake3(d)
    return {
        "name": "fn baseline preset dictionary 1",
        "recipe": "tools/build_compress_dict.py (docs/extensions/nntp-compress-dict.md)",
        "parameters": {"size": SIZE, "segment": SEG, "dgram": D},
        "inputs": [{"path": p, "octets": len(b), "sha256": hashlib.sha256(b).hexdigest()}
                   for p, b in files],
        "octets": len(d),
        "sha256": hashlib.sha256(d).hexdigest(),
        "blake3": b3.hex(),
        "dict_id": int.from_bytes(b3[:4], "big"),
    }


def lisp(d, m):
    lines = [";; generated by tools/build_compress_dict.py; do not edit",
             ";; (docs/extensions/nntp-compress-dict.md, planning/evidence/compress-dict/baseline.json)",
             '(in-package "ACL2")', "",
             "(defconst *fn-lzd-baseline-1*", "  '("]
    row = []
    for i, o in enumerate(d):
        row.append(str(o))
        if len(row) == 24:
            lines.append("    " + " ".join(row))
            row = []
    if row:
        lines.append("    " + " ".join(row))
    lines[-1] += "))"
    lines += ["", "(defconst *fn-lzd-baseline-1-blake3*",
              "  '(" + " ".join(str(o) for o in bytes.fromhex(m["blake3"])) + "))", ""]
    return "\n".join(lines)


def measure(gate, dpath):
    v = open(gate, "rb").read()
    zd = open(dpath, "rb").read()
    n = struct.unpack_from("<I", v, 0)[0]
    dl = struct.unpack_from("<I", v, 4)[0]
    p = 8 + dl
    raw = comp = 0
    for _ in range(n):
        a, c = struct.unpack_from("<II", v, p)
        art = v[p + 8:p + 8 + a]
        p += 8 + a + c
        co = zlib.compressobj(9, zlib.DEFLATED, -15, 9, zlib.Z_DEFAULT_STRATEGY, zd)
        comp += len(co.compress(art) + co.flush(zlib.Z_SYNC_FLUSH))
        raw += a
    return {"articles": n, "raw": raw, "compressed": comp, "ratio": round(raw / comp, 4)}


def main(argv):
    if argv[:1] == ["--measure"]:
        print(json.dumps(measure(argv[1], argv[2])))
        return 0
    out = argv[0]
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    files = inputs(root)
    d = build(files)
    assert len(d) == SIZE, len(d)
    m = manifest(root, files, d)
    os.makedirs(out, exist_ok=True)
    open(os.path.join(out, "baseline.bin"), "wb").write(d)
    open(os.path.join(out, "baseline.json"), "w").write(json.dumps(m, indent=1) + "\n")
    if "--lisp" in argv:
        open(argv[argv.index("--lisp") + 1], "w").write(lisp(d, m))
    print(json.dumps({k: m[k] for k in ("octets", "sha256", "blake3", "dict_id")}))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
