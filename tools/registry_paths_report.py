#!/usr/bin/env python3
"""Report dangling exact path values in requirements/proofs without editing them.

Only JSON is parsed; prose and source code are never evaluated. Resolved means
tracked (including a tracked directory or an extensionless ACL2 book), or named
by the evidence index. Archive availability is a separate check. Dispositions
are proposals: unique basename matches or Git rename history suggest successors;
RETIRE means no successor found, requiring review of the claim before removal.

--check compares the distinct target count to the committed shrink-only ceiling.
It does not waive individual findings, edit registries, or update the baseline.
"""
from __future__ import annotations
import argparse
from collections import defaultdict
import json
from pathlib import Path, PurePosixPath
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
REGISTRIES = ('planning/requirements.json', 'planning/proofs.json')
BASELINE = 'tools/registry_paths_baseline.json'
PATH_VALUE = re.compile(r'[\w.-]+/[^\s\"*<>]+')


def git(root, *args):
    return subprocess.run(['git', '-C', str(root), *args],
                          capture_output=True, text=True, check=False)


def targets(value, location='', ident=''):
    if isinstance(value, dict):
        ident = value.get('id', ident)
        for key, child in value.items():
            yield from targets(child, location + '/' + key, ident)
    elif isinstance(value, list):
        for number, child in enumerate(value):
            yield from targets(child, location + '/' + str(number), ident)
    elif isinstance(value, str) and PATH_VALUE.fullmatch(value):
        yield value.split('#', 1)[0].rstrip('/'), location, ident


def successor(root, path, tracked):
    candidates = sorted(p for p in tracked
                        if PurePosixPath(p).name == PurePosixPath(path).name)
    if len(candidates) == 1:
        return candidates[0], 'unique tracked basename'
    # Full diffs retain the destination outside the old-name pathspec. Follow rename
    # chains only when they are unique, and require a tracked final target.
    seen = set()
    current = path
    while current not in seen:
        seen.add(current)
        log = git(root, 'log', '--format=', '--name-status', '--full-diff',
                  '-M', '--', current)
        renamed = set()
        for line in log.stdout.splitlines():
            parts = line.split('\t')
            if len(parts) == 3 and parts[0].startswith('R') and parts[1] == current:
                renamed.add(parts[2])
        if len(renamed) != 1:
            break
        current = renamed.pop()
        if current in tracked:
            return current, 'git log rename history'
    return None, 'no unique tracked successor found by basename or Git rename history'


def collect(root=ROOT):
    listing = git(root, 'ls-files', '-z')
    if listing.returncode:
        raise ValueError('RegistryPathsError: cannot enumerate tracked files')
    tracked = set(listing.stdout.split('\0')) - {''}
    index_path = root / 'planning/evidence-index.tsv'
    indexed = set()
    if index_path.exists():
        # Validate the index with the common non-fetching parser.
        try:
            from . import evidence_store
        except ImportError:
            import evidence_store
        indexed = set(evidence_store.parse_index(index_path.read_text()))
    names = tracked | indexed
    directories = {str(parent) for p in names for parent in PurePosixPath(p).parents}
    missing = defaultdict(list)
    for registry in REGISTRIES:
        data = json.loads((root / registry).read_text())
        for path, location, ident in targets(data):
            if path in names or path in directories or path + '.lisp' in tracked:
                continue
            missing[path].append(f'{registry}#{location} ({ident})')
    rows = []
    for path, sites in sorted(missing.items()):
        if path.startswith('planning/evidence/'):
            disposition, why = 'UNINDEXED-EVIDENCE', 'no index row names this evidence'
        else:
            new, why = successor(root, path, tracked)
            disposition = 'RENAMED-TO ' + new if new else 'RETIRE'
        rows.append(dict(path=path, sites=sites, disposition=disposition, reason=why))
    return rows


def render(rows):
    lines = ['# Registry paths report', '',
             'Generated by `python3 tools/registry_paths_report.py`. Registries are unchanged.', '',
             f'{len(rows)} distinct unresolved exact path targets. Indexed bytes are not fetched.', '',
             'Dispositions are proposals; RETIRE requires claim review, not automatic deletion.', '']
    for group in ('RENAMED-TO', 'UNINDEXED-EVIDENCE', 'RETIRE'):
        chosen = [r for r in rows if r['disposition'].split()[0] == group]
        lines += [f'## {group} ({len(chosen)})', '', '| target | proposed disposition | basis / citing fields |',
                  '| --- | --- | --- |']
        for row in chosen:
            sites = '<br>'.join(row['sites'])
            lines.append(f"| `{row['path']}` | {row['disposition']} | {row['reason']}; {sites} |")
        lines.append('')
    return '\n'.join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=ROOT)
    parser.add_argument('--baseline', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args(argv)
    rows = collect(args.root)
    if not args.check:
        print(render(rows))
        return 0
    baseline = args.baseline or args.root / BASELINE
    limit = json.loads(baseline.read_text())['maximum_dangling']
    if not isinstance(limit, int) or limit < 0:
        raise ValueError('RegistryPathsError: invalid baseline')
    # A working-tree edit may lower the ceiling, never raise a committed one.
    try:
        rel = baseline.resolve().relative_to(args.root.resolve()).as_posix()
    except ValueError:
        rel = None
    previous = git(args.root, 'show', f'HEAD:{rel}') if rel else None
    if previous and previous.returncode == 0:
        old_limit = json.loads(previous.stdout)['maximum_dangling']
        if limit > old_limit:
            print(f'RegistryPathsBaselineIncrease: {limit} exceeds committed {old_limit}')
            return 1
    print(f'Registry paths: {len(rows)} unresolved; baseline {limit} (shrink-only)')
    return int(len(rows) > limit)


if __name__ == '__main__':
    try:
        raise SystemExit(main())
    except (OSError, ValueError, KeyError) as error:
        raise SystemExit(f'RegistryPathsError: {error}')
