#!/usr/bin/env python3
"""tools/extract/world.py -- the extractor's world is the native image's.

Reads host/native/build.lisp (the session script that saves the image) and
writes, from its forms before `(defttag :fn-native-host)':
  tools/extract/world.lisp       every include-book, as a book (certified
                                 includes; proof_repl starts from it), then
                                 the books the host files include themselves;
  tools/extract/world-host.lisp  every `ld' of a host :program file, in order.
So the functions extracted are the functions the image holds, with the same
attachments in the same order (codec-attach, records-attach-concrete and
payload-arena-attach come first there).  `--check' fails if either file is
not what build.lisp says today.
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BUILD = ROOT / "host" / "native" / "build.lisp"
OUT = ROOT / "tools" / "extract"


def forms():
    text = BUILD.read_text()
    text = text[:text.index("(defttag :fn-native-host)")]
    books = re.findall(r'^\(include-book "([^"]+)"\)', text, re.M)
    hosts = re.findall(r'^\(ld "([^"]+)" :ld-error-action :error\)', text, re.M)
    return books, hosts


def host_books(hosts):
    """The include-books the host files make themselves (their lds followed)."""
    out, seen = [], set()

    def visit(rel):
        path = (ROOT / rel).resolve()
        if path in seen or not path.exists():
            return
        seen.add(path)
        text = path.read_text()
        for m in re.finditer(r'^\s*\((include-book|ld) "([^"]+)"', text, re.M):
            target = (path.parent / m.group(2)).resolve()
            if m.group(1) == "include-book":
                out.append(str(target.relative_to(ROOT)))
            else:
                visit(str(target.relative_to(ROOT)))

    for h in hosts:
        visit(h)
    return out


# The extracted program's own host files, which the image does not load (yet):
# the read-only store open as ACL2 :program code over the host primitives.
EXTRA_HOSTS = ["host/store-open-host.lisp", "host/store-write-host.lisp"]


def render():
    books, hosts = forms()
    hosts = hosts + [h for h in EXTRA_HOSTS if h not in hosts]
    for b in host_books(hosts):
        if b not in books:
            books.append(b)
    head = ("; GENERATED by tools/extract/world.py from host/native/build.lisp: the image's\n"
            "; certified books, in its order.  Do not edit; regenerate.\n")
    world = head + '(in-package "ACL2")\n' + "".join('(include-book "../../%s")\n' % b for b in books)
    host = (head.replace("certified books", "host :program files (ld)") + '(in-package "ACL2")\n'
            + "".join('(ld "../../%s" :ld-error-action :error)\n' % h for h in hosts))
    return {"world.lisp": world, "world-host.lisp": host}


def digest(tree):
    """SHA-256 over the world files, the host files world-host.lisp loads
    (their own lds followed) and the certificate of every book world.lisp
    includes: world_image.sh's cache key."""
    import hashlib
    h = hashlib.sha256()
    x = tree / "tools" / "extract"
    for name in ("world.lisp", "world-host.lisp"):
        h.update(b"%s\n" % name.encode() + (x / name).read_bytes())
    for m in re.finditer(r'^\(ld "\.\./\.\./([^"]+)"', (x / "world-host.lisp").read_text(), re.M):
        h.update(m.group(1).encode() + b"\n" + (tree / m.group(1)).read_bytes())
    for m in re.finditer(r'^\(include-book "\.\./\.\./([^"]+)"\)', (x / "world.lisp").read_text(), re.M):
        cert = tree / (m.group(1) + ".cert")
        h.update(m.group(1).encode() + b"\n" + (cert.read_bytes() if cert.exists() else b"MISSING"))
    return h.hexdigest()[:32]


if __name__ == "__main__":
    if "--digest" in sys.argv:
        print(digest(Path(sys.argv[sys.argv.index("--digest") + 1])))
        sys.exit(0)
    check = "--check" in sys.argv
    bad = 0
    for name, text in render().items():
        path = OUT / name
        if check:
            if not path.exists() or path.read_text() != text:
                print("world.py: %s is not what host/native/build.lisp says; run tools/extract/world.py" % path)
                bad = 1
        else:
            path.write_text(text)
    sys.exit(bad)
