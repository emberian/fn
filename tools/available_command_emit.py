#!/usr/bin/env python3
"""Specialize existing command formatting around the available metadata readers.

This transforms project source, not request data or fn values. The generated
ACL2 dispatcher still obtains every form and its priority from the protocol
row declaration; retained retrieval and chronological discovery stay raw.
"""
from pathlib import Path
import argparse
import re
from proof_repl import forms, head_and_name

ROOT = Path(__file__).resolve().parents[1]
FUNCTIONS = (
    'fn-scat-group-initial', 'fn-nntp-group-result-cat',
    'fn-nntp-listgroup-result-cat', 'fn-nntp-listgroup-command-cat',
    'fn-scat-counts-lines-loop', 'fn-scat-counts-lines',
    'fn-nntp-list-counts-command-cat', 'fn-scat-active-line',
    'fn-scat-active-status-line', 'fn-scat-active-lines-loop',
    'fn-scat-active-lines', 'fn-nntp-list-active-cat',
)
LOCAL_FACTS = ('fn-scat-counts-lines-loop-is-revappend',
               'fn-scat-active-lines-loop-is-revappend')
MAPPING = {name: 'fn-av-' + name[3:] for name in FUNCTIONS + LOCAL_FACTS}
MAPPING['fn-nntp-next-or-last-cat'] = 'fn-av-nntp-next-or-last-cat'
MAPPING.update({
    'fn-scat-group-summary': 'fn-scat-available-summary',
    'fn-scat-group-low': 'fn-scat-available-low',
    'fn-scat-range-numbers': 'fn-scat-available-range-numbers',
    'fn-scat-next-number': 'fn-scat-available-next-number',
    'fn-scat-previous-number': 'fn-scat-available-previous-number',
})
TOKEN = re.compile(r'"(?:[^"\\]|\\.)*"|[^\s()\'`",;]+|.', re.S)


def specialize(form):
    return ''.join(MAPPING.get(m.group().lower(), m.group())
                   if not m.group().startswith('"') else m.group()
                   for m in TOKEN.finditer(form))


def render():
    selected = []
    seen = set()
    for form in forms((ROOT / 'books/served-catalog.lisp').read_text()):
        head, name = head_and_name(form)
        if ((head == 'defun' and name in FUNCTIONS)
                or (head == 'defthm' and name in LOCAL_FACTS)
                or (head == 'verify-guards' and name in FUNCTIONS)):
            selected.append(specialize(form))
            if head == 'defun':
                seen.add(name)
    if seen != set(FUNCTIONS):
        raise ValueError(f'missing source definitions: {set(FUNCTIONS) - seen}')
    aliases = '\n'.join(f'    ({a} . {b})' for a, b in MAPPING.items())
    return '''; Generated by tools/available_command_emit.py; edit the source formatter
; or the specialization map, then regenerate. Raw identity remains retained.
(in-package "ACL2")
(include-book "protocol-served")
(include-book "catalog-available-readers")
(include-book "served-availability")

(local (in-theory (disable (tau-system))))

''' + '\n\n'.join(selected) + '''

; A chosen available neighbour is rendered from its held metadata. The
; availability reader already decides tombstone state; STAT needs no payload
; pread. The raw retrieval commands remain on the retained-history path.
(defun fn-av-held-article (seq fn-cat)
  (declare (xargs :stobjs fn-cat
                  :guard (and (natp seq) (< seq (fn-cat-count fn-cat)))
                  :guard-hints (("Goal" :in-theory (disable fn-cat-count-is-len fn-cat-at-is-nth)))))
  (let ((h (fn-cat-at seq fn-cat)))
    (fn-make-article (fn-record-msgid h) (fn-record-payload h)
                     (fn-record-groups h) (fn-held-numbers h) t (fn-record-stamp h))))

(defun fn-av-nntp-next-or-last-cat (session archive direction v fn-arena fn-cat)
  (declare (xargs :stobjs (fn-arena fn-cat) :guard (natp v) :verify-guards nil))
  (let ((group (fn-nntp-session-group session))
        (current (fn-nntp-session-current session)))
    (if (and group (natp current))
        (let* ((number (if (equal direction :next)
                           (fn-scat-available-next-number group current v fn-cat)
                         (fn-scat-available-previous-number group current v fn-cat)))
               (seq (fn-cat-group-number group number fn-cat)))
          (if (and (posp number) (natp seq) (< seq (fn-cat-count fn-cat))
                   (fn-scv-keptp group number v fn-cat))
              (fn-nntp-make-result
               (fn-nntp-set-cursor session group number)
               (list (fn-nntp-reply-effect
                      (fn-nntp-crlf (fn-nntp-retrieval-initial
                                     :stat number (fn-av-held-article seq fn-cat))))))
            (fn-nntp-single session (if (equal direction :next)
                                        (fn-proto-text "NEXT" :no-next)
                                      (fn-proto-text "LAST" :no-previous)))))
      (fn-nntp-next-or-last session archive direction fn-arena))))

(verify-guards fn-av-nntp-next-or-last-cat
  :hints (("Goal" :in-theory (disable fn-cat-count-is-len fn-cat-at-is-nth))))

; The map changes only selected enumeration helpers in the actual declared
; forms. No second archive/index is allocated in the executable branch.
(defconst *fn-proto-available-command-map*
  '(\n''' + aliases + '''))

(make-event
 `(defun fn-proto-archive-command-available-cat ,*fn-proto-cat-formals*
    (declare (xargs :stobjs (fn-arena fn-cat)
                    :guard (and (natp v)
                                (fn-cat-handles-inp (fn-cat-count fn-cat) fn-arena fn-cat))
                    :verify-guards nil))
    (cond
     ,@(sublis *fn-proto-available-command-map*
               (fn-proto-cat-flat-clauses *fn-proto-served-table*))
     (t (fn-nntp-archive-command-pinned session archive index verdicts
                                       env keyword args fn-arena)))))

; Only enumeration/navigation selects the logical available projection.
; Retrieval identities, overview/header ranges and NEWNEWS chronology stay raw.
(defun fn-av-available-commandp (keyword args)
  (declare (xargs :guard t))
  (or (fn-nntp-keywordp keyword "GROUP")
      (fn-nntp-keywordp keyword "LISTGROUP")
      (fn-nntp-keywordp keyword "NEXT")
      (fn-nntp-keywordp keyword "LAST")
      (and (fn-nntp-keywordp keyword "LIST")
           (or (fn-scat-list-active-formp args)
               (and (consp args)
                    (fn-nntp-keywordp (car args) "COUNTS"))))))

(defun-nx fn-proto-archive-command-available-reference
  (session archive index verdicts env keyword args fn-arena)
  (let* ((selected (fn-av-available-commandp keyword args))
         (view (if selected (fn-nntp-available-archive archive fn-arena) archive))
         (view-index (if selected
                          (fn-gidx-pin-with-control
                           (fn-midx-build (fn-state-articles view))
                           (fn-gidx-build (fn-state-articles view))
                           (fn-gidx-pin-control index))
                        index)))
    (fn-nntp-archive-command-pinned
     session view view-index verdicts env keyword args fn-arena)))

(in-theory (disable fn-proto-archive-command-available-reference))

; A real command-layer consumer, with the same generated session/archive
; routing as fn-scr-command. Production owner/captured-view composition is
; still owed; the old raw-pinned entry and theorem remain unchanged.
(defun fn-scr-command-available (session archive index verdicts env tokens v fn-arena fn-cat)
  (declare (xargs :stobjs (fn-arena fn-cat)
                  :guard (and (natp v)
                              (fn-cat-handles-inp (fn-cat-count fn-cat) fn-arena fn-cat))
                  :verify-guards nil))
  (fn-nntp-command-dispatch
   (fn-proto-archive-command-available-cat
    session archive index verdicts env keyword args v fn-arena fn-cat)
   :pinned t))

; No raw-pinned equality claim: metadata availability has a distinct selective
; reference and requires captured facts completeness. Guard/proof/image and
; actual owner route propagation are explicitly pending at this source.
'''


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    path = ROOT / 'books/served-available-commands.lisp'
    text = render()
    if args.check:
        return 0 if path.exists() and path.read_text() == text else 1
    path.write_text(text)
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
