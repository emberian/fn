     site=self.fresh();call=f'({op} {" ".join(values)})'
     if op in ('list','cons'):
      event=f"(list (list :constructor {len(values) if op=='list' else 1} '{site}))"
     elif op=='ceiling':event=f"(list (list :ceiling (list {' '.join(values)}) '{site}))"
     else:event=f"(list (list :borrow '{op} (list {' '.join(values)}) '{site}))"
