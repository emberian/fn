#!/usr/bin/env python3
"""The registry half of `defevent': event families' codes, generated and kept stable.

`(defevent FAMILY :version N :codes ((KIND CODE) ...) :reserved ((CODE "why"))
...)` (books/defevent.lisp) generates a family's encoder, the replay's
decoder and a recognizer.  This reads every such form in books/ with the
ledger's non-evaluating reader and

* GENERATES planning/events.json: per family its book, version, codes,
  reserved codes (the family's other entries and every retired code), the
  fields that carry recorded nondeterminism, and the generated function
  names -- what a test or a reader of a journal line looks a code up in,
  instead of a copy of the number;
* CHECKS STABILITY against the registry as committed at a base revision
  (default origin/dev; `--base REV`): for every family there,
    - a KIND keeps its CODE, unless the form's :version is greater;
    - a CODE never names a different KIND at the same version;
    - a CODE that left :codes is :reserved (retired), so it is never reused;
    - :version never decreases, and a family is never removed.
  This is the check the macro cannot make: the macro sees one revision, the
  history is git's.

    python3 tools/event_emit.py            # report
    python3 tools/event_emit.py --check    # exit 1 on any finding (make check)
    python3 tools/event_emit.py --write    # regenerate planning/events.json
    python3 tools/event_emit.py --get fn-otm-word became-stalled   # a code
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from tools import ledger  # noqa: E402

REGISTRY = ROOT / "planning" / "events.json"
RELATIVE = "planning/events.json"


def _sym(x) -> str:
    return str(x).lower()


def _kw(x) -> str:
    return _sym(x).lstrip(":")


def families(root: Path = ROOT) -> dict[str, dict]:
    found: dict[str, dict] = {}
    for path in sorted((root / "books").glob("*.lisp")):
        text = path.read_text(encoding="utf-8")
        if "(defevent " not in text:
            continue
        relative = path.relative_to(root).as_posix()
        for form, line in ledger.Reader(text).top_level():
            if ledger.head(form) != "defevent" or relative == "books/defevent.lisp":
                continue
            kv = ledger.keyword_plist(form[2:])
            get = lambda key: kv.get(key)  # noqa: E731
            name = _sym(form[1])
            found[name] = {
                "book": relative,
                "version": int(get(":version")),
                "codes": {_kw(k): int(c) for k, c in get(":codes") or []},
                "reserved": {str(int(c)): {"name": _kw(n), "why": why}
                             for c, n, why in get(":reserved") or []},
                "recorded": {_sym(f): why for f, why in get(":recorded") or []},
                "otherwise": int(get(":otherwise")),
                "encode": _sym(get(":encode")),
                "decode": _sym(get(":decode")) if get(":decode") else None,
                "recognizer": _sym(get(":recognizer")) if get(":recognizer") else None,
            }
    return found


def render(fams: dict[str, dict]) -> str:
    doc = {
        "schema_version": 1,
        "description": ("GENERATED by tools/event_emit.py from the defevent forms "
                        "(books/defevent.lisp) in books/.  Do not edit; regenerate.  "
                        "A code's meaning is stable: tools/event_emit.py --check refuses a "
                        "renumbering the family's :version and :reserved do not account for."),
        "families": {name: fams[name] for name in sorted(fams)},
    }
    return json.dumps(doc, indent=2) + "\n"


def committed(base: str) -> dict | None:
    try:
        out = subprocess.run(["git", "-C", str(ROOT), "show", "{}:{}".format(base, RELATIVE)],
                             stdout=subprocess.PIPE, stderr=subprocess.DEVNULL, check=True)
    except (subprocess.CalledProcessError, OSError):
        return None
    return json.loads(out.stdout.decode("utf-8")).get("families", {})


def stability(old: dict, new: dict) -> list[str]:
    out: list[str] = []
    for name, was in sorted(old.items()):
        now = new.get(name)
        if now is None:
            out.append("{}: the family was removed; its codes would be free to reuse".format(name))
            continue
        if now["version"] < was["version"]:
            out.append("{}: :version went from {} to {}".format(name, was["version"], now["version"]))
        bumped = now["version"] > was["version"]
        by_code = {c: k for k, c in now["codes"].items()}
        for kind, code in sorted(was["codes"].items()):
            if now["codes"].get(kind, code) != code and not bumped:
                out.append("{}: {} was code {} and is now {} at the same :version {}".format(
                    name, kind, code, now["codes"][kind], now["version"]))
            if code in by_code and by_code[code] != kind and not bumped:
                out.append("{}: code {} named {} and now names {} at the same :version".format(
                    name, code, kind, by_code[code]))
            if code not in by_code and str(code) not in now["reserved"]:
                out.append("{}: code {} ({}) left :codes without a :reserved entry; a retired "
                           "code is reserved so no kind reuses it".format(name, code, kind))
        for code, row in sorted(was["reserved"].items()):
            if int(code) in by_code and not bumped:
                out.append("{}: reserved code {} ({}) is now {}".format(
                    name, code, row["name"], by_code[int(code)]))
            elif code not in now["reserved"] and int(code) not in by_code:
                out.append("{}: reserved code {} ({}) left :reserved; it would be free "
                           "to reuse".format(name, code, row["name"]))
    return out


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--base", default="origin/dev")
    parser.add_argument("--get", nargs=2, metavar=("FAMILY", "KIND"))
    args = parser.parse_args(argv)
    fams = families()
    if args.get:
        print(fams[args.get[0]]["codes"][args.get[1]])
        return 0
    if args.write:
        REGISTRY.write_text(render(fams))
    problems: list[str] = []
    if not REGISTRY.is_file() or REGISTRY.read_text() != render(fams):
        problems.append("planning/events.json is not what the defevent forms say; "
                        "run tools/event_emit.py --write")
    old = committed(args.base)
    if old is not None:
        problems += stability(old, fams)
    print("event_emit: {} famil{}; stability against {}: {}; {} finding(s)".format(
        len(fams), "y" if len(fams) == 1 else "ies", args.base,
        "checked" if old is not None else "no committed registry there yet", len(problems)))
    for problem in problems:
        print("  " + problem)
    return 1 if (args.check and problems) else 0


if __name__ == "__main__":
    raise SystemExit(main())
