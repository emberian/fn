#!/usr/bin/env python3
"""Take the :rewrite class off the hazard rules a census names.

A hazard rule (tools/hazard_rules_check.py) is a :rewrite rule whose
left-hand side is a structural primitive applied to distinct variables --
(car x), (consp x), (member-equal x y) -- so every book that includes it
tries it on every such term.  This tool reads the census TSV that
`hazard_rules_check.py --census' writes (theorem, book:line, head) and, for
each theorem, edits its `defthm'/`defthmd' form in the named book:

    no :rule-classes            -> add `:rule-classes nil'
    :rule-classes :rewrite      -> `:rule-classes nil'
    :rule-classes (... :rewrite (:rewrite ...) ...)
                                -> the list without its :rewrite entries
                                   (`nil' when nothing else is left)

Nothing else in the file changes (tools/lisp_rewrite.py edits by span).
The theorem's statement is untouched; consumers that used it as a rewrite
rule take it by :use.  A row whose theorem has no defthm form of that name
in the book (generated by a macro), or whose :rule-classes is something this
tool does not read, is refused by name and printed as the residual.

    tools/hazard_rule_classes.py CENSUS.tsv [--only BOOK...] [--apply]
    tools/hazard_rule_classes.py CENSUS.tsv --disable [--only BOOK...] [--apply]

Without --apply it prints the plan and writes nothing.

--disable is the other move, and the one that keeps the book's own proofs:
the rule stays a :rewrite rule inside its book, and one
`(in-theory (disable ...))' event appended at the end of the book (exported,
so it holds in every book that includes this one) names the book's census
theorems.  A consumer that wants a rule enables it or takes it by :use.
Taking the class off (the default move) also breaks every `(disable NAME)'
that names a theorem left without runes, and every later proof in the same
book that used the rule.
"""
from __future__ import annotations

import argparse
import csv
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from lisp_rewrite import Atom, Lst, Pre, parse, write  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent


class Refuse(Exception):
    pass


def _walk(node):
    if isinstance(node, Pre):
        yield from _walk(node.node)
    elif isinstance(node, Lst):
        yield node
        for x in node.items:
            yield from _walk(x)


def _head(lst):
    if lst.items and isinstance(lst.items[0], Atom):
        return lst.items[0].low
    return None


def find_defthm(forms, name):
    hits = []
    for f in forms:
        for lst in _walk(f):
            if (_head(lst) in ("defthm", "defthmd") and len(lst.items) > 2
                    and isinstance(lst.items[1], Atom) and lst.items[1].low == name):
                hits.append(lst)
    if len(hits) != 1:
        raise Refuse("generated" if not hits else "ambiguous")
    return hits[0]


def _is_rewrite(x):
    if isinstance(x, Atom):
        return x.low == ":rewrite"
    if isinstance(x, Lst):
        return _head(x) == ":rewrite"
    return False


def _rule_classes(form):
    items = form.items
    i = 3
    while i + 1 < len(items):
        k = items[i]
        if isinstance(k, Atom) and k.low == ":rule-classes":
            v = items[i + 1]
            return v.node if isinstance(v, Pre) else v
        i += 2
    return None


def edit_for(text, form):
    """(start, end, replacement) taking :rewrite off FORM's rule classes."""
    items = form.items
    # keyword arguments start after the formula (items[2])
    i = 3
    while i + 1 < len(items):
        k = items[i]
        if isinstance(k, Atom) and k.low == ":rule-classes":
            v = items[i + 1]
            if isinstance(v, Atom):
                if v.low == ":rewrite":
                    return (v.start, v.end, "nil")
                if v.low == "nil":
                    raise Refuse("already-nil")
                raise Refuse(f"rule-classes {v.text}")
            if isinstance(v, Pre) and v.prefix == "'" and isinstance(v.node, Lst):
                v_list, outer = v.node, v
            elif isinstance(v, Lst):
                v_list, outer = v, v
            else:
                raise Refuse("rule-classes form")
            keep = [x for x in v_list.items if not _is_rewrite(x)]
            if len(keep) == len(v_list.items):
                raise Refuse("no :rewrite class")
            if not keep:
                return (outer.start, outer.end, "nil")
            new = "(" + " ".join(text[x.start:x.end] for x in keep) + ")"
            return (v_list.start, v_list.end, new)
        i += 2
    formula = items[2]
    return (formula.end, formula.end, "\n :rule-classes nil")


def plan(census, only=None):
    rows = list(csv.DictReader(open(census), delimiter="\t"))
    by_book = {}
    for r in rows:
        book = r["site"].split(":")[0]
        if only and book not in only:
            continue
        by_book.setdefault(book, []).append(r["theorem"].lower())
    edits, resid = {}, []
    for book, names in sorted(by_book.items()):
        text = (ROOT / book).read_text()
        forms = parse(text).forms
        for name in names:
            try:
                edits.setdefault(book, []).append((name, edit_for(text, find_defthm(forms, name))))
            except Refuse as r:
                resid.append((book, name, str(r)))
    return edits, resid


DISABLE_HEAD = "; Hazard rules (tools/hazard_rule_classes.py --disable): :rewrite rules on\n" \
    "; a structural primitive of bare variables, kept for this book's proofs\n" \
    "; and disabled for every book that includes it (enable or :use them).\n"


def disable_plan(census, only=None):
    rows = list(csv.DictReader(open(census), delimiter="\t"))
    by_book, resid = {}, []
    for r in rows:
        book = r["site"].split(":")[0]
        if only and book not in only:
            continue
        name = r["theorem"].lower()
        text = (ROOT / book).read_text()
        try:
            form = find_defthm(parse(text).forms, name)
        except Refuse as e:
            resid.append((book, name, str(e)))
            continue
        if form.items[0].low == "defthmd":
            resid.append((book, name, "defthmd: already disabled"))
            continue
        rune = name
        rc = _rule_classes(form)
        if isinstance(rc, Lst) and any(not _is_rewrite(x) for x in rc.items):
            # keep the other classes (:forward-chaining ...) working: disable
            # only the :rewrite rune, which is (:rewrite NAME) when the list
            # has one bare :rewrite
            if [x for x in rc.items if _is_rewrite(x)] != [x for x in rc.items
                                                          if isinstance(x, Atom) and x.low == ":rewrite"] \
                    or sum(1 for x in rc.items if _is_rewrite(x)) != 1:
                resid.append((book, name, "rewrite corollary in a class list"))
                continue
            rune = f"(:rewrite {name})"
        if rune not in by_book.setdefault(book, []):
            by_book[book].append(rune)
    edits = {}
    for book, names in sorted(by_book.items()):
        text = (ROOT / book).read_text()
        body = "(in-theory (disable " + "\n                    ".join(names) + "))\n"
        sep = "" if text.endswith("\n\n") else ("" if text.endswith("\n") else "\n")
        edits[book] = [(n, (len(text), len(text), sep + "\n" + DISABLE_HEAD + body)) for n in names[:1]]
        edits[book] += [(n, (len(text), len(text), "")) for n in names[1:]]
    return edits, resid


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("census")
    ap.add_argument("--only", nargs="*")
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--disable", action="store_true")
    a = ap.parse_args(argv)
    only = set(a.only) if a.only else None
    edits, resid = (disable_plan if a.disable else plan)(a.census, only)
    for book, es in edits.items():
        for name, (s, e, r) in es:
            print(f"{book}: {name}: {'insert' if s == e else 'replace'} {r.strip()[:60]!r}")
        if a.apply:
            p = ROOT / book
            p.write_text(write(p.read_text(), [e for _, e in es]))
    for book, name, why in resid:
        print(f"REFUSED {book}: {name}: {why}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
