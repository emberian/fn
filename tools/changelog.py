#!/usr/bin/env python3
"""CHANGELOG.md from the git history: one line per merged lane, by capability.

    python3 tools/changelog.py                 # print for HEAD
    python3 tools/changelog.py --write         # write CHANGELOG.md for HEAD
    python3 tools/changelog.py --check         # exit 1 unless CHANGELOG.md is current
    python3 tools/changelog.py --rev REV --since BASE

The source is dev's first-parent history from BASE to REV.  BASE defaults to
the previous release's tag: the newest v* tag that comes before VERSION in
the release sequence (D37, tools/release_sequence.py; by sequence position,
never by number).  With no such tag (the first release, 6.6.0) it is the
commit that added the Fable mandate,
planning/handoff-2026-09-25-fable-mandate.md.  Every lane merge on it is
one line: the lane's name and the first clause of its merge message.  A merge that a later first-parent commit
reverts (its body says `Reverts HASH' or git's `This reverts commit HASH')
is left out and listed under "Reverted".  Direct commits (registry
regeneration, certification records, sweeps, chores) are not changes a
reader of the release sees and are not listed; their count is.  The range
ends at the last lane merge, so the file committed after it (the cut's own
commit) is regenerated byte for byte at the cut.

Capabilities are decided by the lane's name against CAPABILITIES below
(first match wins); a lane no rule names goes under "Other", which is the
signal to add a rule, not an error.  The file carries a VERSION line (the
file VERSION at REV) and the range, so a later cut regenerates it by
running this again.  Nothing here reads the network or writes anything but
CHANGELOG.md.
"""
from __future__ import annotations

import argparse
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import release_sequence  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
MANDATE = "planning/handoff-2026-09-25-fable-mandate.md"

# (heading, lane-name pattern).  Order matters: the first match wins.
CAPABILITIES: list[tuple[str, str]] = [
    ("Release, packaging and deployment",
     r"^(release|deploy|image|heap|runtime|crypto-deps|frozen|migration-removal|launcher|"
     r"public-node|node-disk|fleet)"),
    ("Qualification, tests and tooling",
     r"^(qual|harness|tooling|friction|native-harness|assurance|burndown|cut-map|"
     r"carrier-bound|throughput-gate|hot-path-checker|ten-second|review|"
     r"consolidation-design|w\d|topic-|test-)"),
    ("Delay-tolerant networking (BP, TCPCL)",
     r"^(bp-|mission|multi-peer-relay|dtn|tcpcl)"),
    ("TLS and public exposure",
     r"^(tls|public-|hostile|exposure|sanding|listener)"),
    ("Accounts, keys and authority",
     r"^(keys-and-accounts|friends-accounts|login|key-|signed-history|group-access|"
     r"group-policy|newsreader-cancel)"),
    ("Peering and transit",
     r"^(transit|peer|peering|friends-peer|source-corpus|visibility-join|control-across|"
     r"connection-multiplexing)"),
    ("Reading and posting (NNTP)",
     r"^(reader|usenet-headers|served|nntp|moderated|header-limits|group-)"),
    ("Agents (consumers)",
     r"^(consumer|community)"),
    ("Storage, checkpoints and recovery",
     r"^(checkpoint|pack-chain|reclaim|store|catalog|records|rep-wave|bounds|"
     r"width|capacity|caps-to-profile|power-loss|group-commit|acceptance-payload|"
     r"marker|profile-open|rollback|storage|open-by-index|index-stobjs|"
     r"publish-program|commit-regression|history)"),
    ("Operator and configuration",
     r"^(operator|config|live|outcome-algebra|adapter|owner|service-envelope|"
     r"control-reply)"),
    ("Performance",
     r"^(hot-path|perf|scale|served-path-scale|signed-post|post-identity|over-number|"
     r"egress|ingress)"),
]

MERGE_RE = re.compile(r"^(?:Batch [A-Z]+: )?[Mm]erge lane/(?P<lane>[A-Za-z0-9._-]+)")
REVERT_RE = re.compile(r"(?:This reverts commit|Reverts)\s+([0-9a-f]{7,40})")


def git(*args: str) -> str:
    return subprocess.run(["git", "-C", str(ROOT), *args], check=True,
                          capture_output=True, text=True).stdout


def first_clause(text: str, limit: int = 150) -> str:
    """The message's first clause: up to the first `; ' or `. ', at most
    LIMIT characters, cut at a word boundary."""
    text = " ".join(text.split())
    # Registry ids at the front ("PRF-222, NNT-046, per-login group access")
    # are the ledger's business, not the reader's.
    text = re.sub(r"^(?:(?:[A-Z]{2,4}-\d+|D\d+)(?:\s*\([^)]*\))?[,;:]?\s+)+", "", text)
    cut = len(text)
    for sep in ("; ", ". "):
        i = text.find(sep)
        if 0 <= i < cut:
            cut = i
    text = text[:cut].rstrip(".;:, ")
    if len(text) > limit:
        text = text[:limit].rsplit(" ", 1)[0].rstrip(".;:,( ") + " ..."
    return text


def merge_parts(subject: str) -> tuple[str, str] | None:
    """(lane, message) of a lane merge's subject: `[Batch X: ]Merge lane/NAME
    [(balanced parenthetical)][:] MESSAGE'."""
    m = MERGE_RE.match(subject)
    if not m:
        return None
    rest = subject[m.end():].lstrip()
    if rest.startswith("("):
        depth = 0
        for i, ch in enumerate(rest):
            depth += ch == "("
            depth -= ch == ")"
            if depth == 0:
                rest = rest[i + 1:]
                break
    if not rest.startswith(":") and "): " in rest:
        # `(a), more words (b; c): MESSAGE': the message follows the last
        # parenthetical of the subject's head.
        rest = rest.split("): ", 1)[1]
    rest = rest.lstrip(":;, ").strip()
    return m.group("lane"), rest or subject


def capability(lane: str) -> str:
    for heading, pattern in CAPABILITIES:
        if re.search(pattern, lane):
            return heading
    return "Other"


def commits(since: str, rev: str) -> list[tuple[str, int, str, str]]:
    """(hash, parent count, subject, body) on the first-parent path, oldest first."""
    raw = git("log", "--first-parent", "--reverse", "--format=%H%x00%P%x00%s%x00%b%x1e",
              f"{since}..{rev}")
    out = []
    for record in raw.split("\x1e"):
        record = record.strip("\n")
        if not record:
            continue
        h, parents, subject, body = record.split("\x00", 3)
        out.append((h, len(parents.split()), subject, body))
    return out


def version_at(rev: str) -> str:
    """VERSION at REV; for HEAD the working tree's file, so a commit that
    changes VERSION and CHANGELOG.md together agrees with itself (the cut's
    own commit)."""
    full = git("rev-parse", rev).strip()
    if full == git("rev-parse", "HEAD").strip() and (ROOT / "VERSION").exists():
        return (ROOT / "VERSION").read_text().splitlines()[0].strip()
    if subprocess.run(["git", "-C", str(ROOT), "cat-file", "-e", f"{full}:VERSION"],
                      capture_output=True).returncode == 0:
        return git("show", f"{full}:VERSION").splitlines()[0].strip()
    return "unversioned"


def previous_release(version: str, tags: list[str]) -> str | None:
    """The newest v* tag before VERSION in the release sequence (D37), or
    None.  Tags outside the sequence are not releases and are ignored."""
    try:
        here = release_sequence.position(version)
    except ValueError:
        here = None
    before = []
    for t in tags:
        if not t.startswith("v") or t[1:] == version:
            continue
        try:
            p = release_sequence.position(t[1:])
        except ValueError:
            continue
        if here is None or p < here:
            before.append(t[1:])
    last = release_sequence.newest(before)
    return f"v{last}" if last else None


def render(rev: str, since: str, since_label: str = "the Fable mandate") -> str:
    full = git("rev-parse", rev).strip()
    base = git("rev-parse", since).strip()
    version = version_at(full)
    history = commits(base, full)
    reverted: set[str] = set()
    for h, _, subject, body in history:
        if subject.startswith("Revert") or re.search(r"\brevert the \S+ merge\b", subject, re.I):
            for m in REVERT_RE.finditer(subject + "\n" + body):
                reverted.add(m.group(1))
            m = re.search(r"merge \(([0-9a-f]{7,40})\)", subject)
            if m:
                reverted.add(m.group(1))
    # The range ends at the last lane merge (or the revert of one), so the
    # file a cut commits after it is what this writes again at the cut.
    def ends_range(n: int, s: str) -> bool:
        return (n > 1 and merge_parts(s) is not None) or bool(
            re.search(r"\brevert the \S+ merge\b", s, re.I))
    last = max((i for i, (_, n, s, _) in enumerate(history) if ends_range(n, s)),
               default=len(history) - 1)
    history = history[:last + 1]
    end = history[-1][0] if history else base
    groups: dict[str, list[str]] = {}
    gone: list[str] = []
    direct = 0
    seen: set[str] = set()
    for h, nparents, subject, body in history:
        parts = merge_parts(subject) if nparents > 1 else None
        if not parts:
            direct += 1
            continue
        lane, message = parts
        line = f"- **{lane}**: {first_clause(message)}"
        if any(h.startswith(r) for r in reverted):
            gone.append(f"- **{lane}** ({h[:9]}): {first_clause(message)}")
            continue
        if lane in seen:
            line = f"- **{lane}** (again): {first_clause(message)}"
        seen.add(lane)
        groups.setdefault(capability(lane), []).append(line)
    order = [h for h, _ in CAPABILITIES] + ["Other"]
    if since_label == "the Fable mandate":
        head = [f"fn {version}: the changes merged into dev from {base[:12]} (the Fable",
                f"mandate) to {end[:12]}, one line per merged lane, grouped by capability."]
    else:
        head = [f"fn {version}: the changes merged into dev from {base[:12]} ({since_label})",
                f"to {end[:12]}, one line per merged lane, grouped by capability."]
    merged = sum(len(v) for v in groups.values())
    out = [
        "# Changelog",
        "",
        *head,
        f"Generated by `tools/changelog.py` ({merged} lane merges, {len(gone)} reverted,",
        f"{direct} direct commits not listed); regenerate it, never edit it.",
        "",
    ]
    for heading in order:
        if heading in groups:
            out += [f"## {heading}", ""] + groups[heading] + [""]
    if gone:
        out += ["## Reverted (merged, then reverted; not in this release)", ""] + gone + [""]
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--rev", default="HEAD")
    ap.add_argument("--since", default=None,
                    help="the base commit (default: the previous release's tag in the release sequence, else the commit that added %s)" % MANDATE)
    mode = ap.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--check", action="store_true")
    ap.add_argument("--output", default=str(ROOT / "CHANGELOG.md"))
    a = ap.parse_args(argv)
    label = "the Fable mandate"
    since = a.since
    if since is None:
        prev = previous_release(version_at(a.rev), git("tag", "-l", "v*").split())
        if prev:
            since, label = prev, f"release {prev}"
        else:
            since = git("log", "--diff-filter=A", "--format=%H", a.rev, "--",
                        MANDATE).split()[-1]
    else:
        label = f"the given base {since}"
    text = render(a.rev, since, label)
    path = Path(a.output)
    if a.write:
        path.write_text(text)
        print(f"changelog: wrote {path}")
        return 0
    if a.check:
        if not path.exists() or path.read_text() != text:
            print(f"changelog: {path} is not what tools/changelog.py --rev {a.rev} writes;"
                  " run it with --write", file=sys.stderr)
            return 1
        print("changelog: current")
        return 0
    sys.stdout.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
