#!/usr/bin/env python3
"""The host's entry wrappers, generated.

A host file used to carry hand-written one-call entries,

    (defun fn-x-host-run (a b) (declare (xargs :mode :program)) (fn-x-run a b))

each an exact alias of a book function under a name the interface rows declare.  The
alias is data: tools/entry_wrappers.json holds, per host file, one row per entry --
[NAME, FORMALS, PREFIX, CALLEE], PREFIX being the docstring and declare forms in source
order -- and `interface_emit.py --write` (or this file's --write) renders, per host file, one certified book

    books/entries-<host file stem>.lisp  =  (in-package) (include-book of the books
    NAME's callee and guard name) (defun NAME FORMALS PREFIX... (CALLEE FORMALS...))...

The host file includes that book where its first alias used to be; its `definterface`
rows stay where they are.  An alias is never written twice: --check fails when a host
file defines a name the table emits, when a generated book differs from what the table
says, or when a host file does not include its book exactly once.

    python3 tools/interface_entries.py --check
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

TABLE = "tools/entry_wrappers.json"
HEADER = ("; GENERATED by tools/interface_entries.py from tools/entry_wrappers.json.\n"
          "; Do not edit; regenerate with `python3 tools/interface_entries.py --write'.\n")


def stem(source: str) -> str:
    return Path(source).stem


def output_relative(source: str) -> str:
    return "books/entries-{}.lisp".format(stem(source))


def include_form(source: str) -> str:
    return '(include-book "../books/entries-{}")'.format(stem(source))


def load_table(root: Path = ROOT) -> dict[str, list[list]]:
    path = root / TABLE
    if not path.is_file():
        return {}
    return json.loads(path.read_text(encoding="utf-8"))


def save_table(table: dict[str, list[list]], root: Path = ROOT) -> None:
    ordered = {source: table[source] for source in sorted(table) if table[source]}
    text = "{\n" + ",\n".join(
        "  {}: [\n{}\n  ]".format(
            json.dumps(source),
            ",\n".join("    " + json.dumps(row) for row in rows))
        for source, rows in ordered.items()) + "\n}\n"
    (root / TABLE).write_text(text, encoding="utf-8")


def render(source: str, rows: list[list], package: str, book_paths: list[str]) -> str:
    forms = [HEADER.rstrip("\n"), package]
    for book in book_paths:
        forms.append('(include-book "{}")'.format(Path(book).with_suffix("").name))
    for name, formals, prefix, callee in rows:
        args = formals[1:-1]
        lines = ["(defun {} {}".format(name, formals)]
        lines.extend("  " + item for item in prefix)
        lines.append("  ({}{}))".format(callee, " " + args if args else ""))
        forms.append("\n".join(lines))
    return "\n\n".join(forms) + "\n"


AGGREGATE = "books/entries.lisp"


def aggregate(sources) -> str:
    """The one certification root over every generated entries book: a host file is
    ld'd, not certified, so nothing else would reach its book."""
    forms = [HEADER.rstrip("\n"), '(in-package "ACL2")']
    forms.extend('(include-book "entries-{}")'.format(stem(source)) for source in sorted(sources))
    return "\n\n".join(forms) + "\n"


def emitted(root: Path = ROOT) -> dict[str, str]:
    """output path -> generated text, for every host file in the table (and the root)."""
    from tools import host_wrappers as hw
    index = hw.book_index(root)
    out = {}
    for source, rows in sorted(load_table(root).items()):
        books = []
        for _name, _formals, prefix, callee in rows:
            for token in set(hw.TOKEN.findall(hw.blank(" ".join([callee, *prefix])).lower())):
                book = hw.defining_book(index, token)
                if book and book not in books:
                    books.append(book)
        out[output_relative(source)] = render(source, rows, '(in-package "ACL2")', sorted(books))
    if out:
        out[AGGREGATE] = aggregate(load_table(root))
    return out


def write(root: Path = ROOT) -> list[str]:
    changed = []
    for relative, text in emitted(root).items():
        path = root / relative
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            path.write_text(text, encoding="utf-8")
            changed.append(relative)
    return changed


def findings(root: Path = ROOT) -> list[str]:
    from tools import host_wrappers as hw, ledger
    out = []
    table = load_table(root)
    expected = emitted(root)
    present = {p.relative_to(root).as_posix() for p in (root / "books").glob("entries-*.lisp")}
    if expected and "books/entries" not in ledger.makefile_roots(root):
        out.append("Makefile ACL2_BOOKS must list books/entries, the root of the generated entries")
    for relative in sorted(present - set(expected)):
        out.append("{} is generated for no row of {}".format(relative, TABLE))
    for relative, text in expected.items():
        path = root / relative
        if not path.is_file() or path.read_text(encoding="utf-8") != text:
            out.append("{} is not what {} says; run tools/interface_emit.py --write".format(
                relative, TABLE))
    for source, rows in table.items():
        host = hw.blank((root / source).read_text(encoding="utf-8"))
        names = {row[0] for row in rows}
        for name in sorted(names):
            if re.search(r"\(defun\s+" + re.escape(name) + r"[\s(]", host, re.I):
                out.append("{} defines {}, which {} emits".format(source, name, TABLE))
        raw = (root / source).read_text(encoding="utf-8")
        if len(re.findall(r"(?m)^" + re.escape(include_form(source)) + r"\s*$", raw)) != 1:
            out.append("{} must include its generated entries exactly once with {}".format(
                source, include_form(source)))
        if len(names) != len(rows):
            out.append("{} lists a name twice in {}".format(source, TABLE))
    return out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--write", action="store_true")
    ap.add_argument("--root", default=str(ROOT))
    args = ap.parse_args(argv)
    root = Path(args.root)
    if args.write:
        for relative in write(root):
            print("wrote", relative)
    found = findings(root)
    for line in found:
        print(line)
    table = load_table(root)
    print("interface_entries: {} entries in {} host files".format(
        sum(len(rows) for rows in table.values()), len(table)))
    return 1 if found and args.check else 0


if __name__ == "__main__":
    sys.exit(main())
