#!/usr/bin/env python3
"""The release image's book roots from a closure.lisp report (lane
runtime-image, 2026-09-26).

    closure.py REPORT [--root TREE] [--write host/native/release-roots.lisp]

REPORT holds closure.lisp's RI-BOOK lines (book, functions, theorems, and the
number of the host's executable-closure functions the book introduces).  A
book is KEPT when it introduces a reached function, carries a guard
verification (`verify-guards') or an attachment (`defattach') -- execution
events that live beside theorems -- or is a non-local include-book ancestor
of a kept book (ACL2 loads those whether the image wants them or not).  Every
other book is theorem-only for the running node and is EXCLUDED: it stays in
the certified source and the manifest.  --write emits the include-book list
(kept books that no other kept book includes, in the order the production
world included them).
"""
from __future__ import annotations

import argparse
from pathlib import Path
import re
import sys

INCLUDE = re.compile(r'\((local\s+)?\(?\s*include-book\s+"([^"]+)"', re.I)
EXEC_EVENT = re.compile(r'\((verify-guards|defattach)\b', re.I)


def strip_comments(text):
    out = []
    for line in text.splitlines():
        i = line.find(";")
        out.append(line if i < 0 else line[:i])
    text = "\n".join(out)
    return re.sub(r"#\|.*?\|#", "", text, flags=re.S)


def includes(root: Path, book: str):
    """Non-local include-book targets of BOOK ("books/x.lisp"), as book names."""
    path = root / book
    text = strip_comments(path.read_text(encoding="utf-8", errors="replace"))
    out = []
    for m in re.finditer(r'(\(local\s+)?\(include-book\s+"([^"]+)"([^)]*)\)', text, re.I):
        if m.group(1) or ":dir" in m.group(3).lower():
            continue
        target = (path.parent / (m.group(2) + ".lisp")).resolve()
        try:
            out.append(str(target.relative_to(root.resolve())))
        except ValueError:
            pass
    return out


def main(argv=None):
    p = argparse.ArgumentParser()
    p.add_argument("report")
    p.add_argument("--root", default=".")
    p.add_argument("--write")
    a = p.parse_args(argv)
    root = Path(a.root)
    rows = []
    for line in Path(a.report).read_text().splitlines():
        m = re.search(r"RI-BOOK (\S+) fns=(\d+) thms=(\d+) reached=(\d+)", line)
        if m:
            rows.append((m.group(1), int(m.group(3)), int(m.group(4))))
    fn = [r for r in rows if r[0].startswith("books/")]
    system = [r for r in rows if not r[0].startswith("books/")]
    order = [r[0] for r in reversed(fn)]  # the include-book-alist is newest first
    thms = {r[0]: r[1] for r in fn}
    seed = set()
    why = {}
    for book, _, reached in fn:
        text = strip_comments((root / book).read_text(encoding="utf-8", errors="replace"))
        if reached:
            seed.add(book); why[book] = "defines %d reached" % reached
        elif EXEC_EVENT.search(text):
            seed.add(book); why[book] = "verify-guards/defattach"
    kept, stack = set(), list(seed)
    graph = {}
    while stack:
        b = stack.pop()
        if b in kept:
            continue
        kept.add(b)
        graph[b] = includes(root, b)
        for c in graph[b]:
            if c not in kept:
                why.setdefault(c, "ancestor")
                stack.append(c)
    fnset = {r[0] for r in fn}
    excluded = [b for b in order if b not in kept]
    ancestors = set()
    for b in kept:
        ancestors.update(graph.get(b, []))
    roots = [b for b in order if b in kept and b not in ancestors]
    print("fn books in the production world: %d (%d theorems); system books: %d (%d theorems)"
          % (len(fn), sum(thms.values()), len(system), sum(r[1] for r in system)))
    print("kept: %d books (%d theorems): %d define reached functions, %d guard/attachment "
          "books, %d ancestors only" % (
              len(kept & fnset), sum(thms.get(b, 0) for b in kept),
              sum(1 for b in kept if why.get(b, "").startswith("defines")),
              sum(1 for b in kept if why.get(b) == "verify-guards/defattach"),
              sum(1 for b in kept if why.get(b) == "ancestor")))
    print("excluded (theorem-only for the running node): %d books (%d theorems)"
          % (len(excluded), sum(thms.get(b, 0) for b in excluded)))
    for b in excluded:
        print("  - %s (%d theorems)" % (b, thms.get(b, 0)))
    print("release roots: %d" % len(roots))
    if a.write:
        lines = ["; host/native/release-roots.lisp -- GENERATED by tools/runtime_image/closure.py",
                 "; from the production world's closure report; do not edit by hand.  The",
                 "; release image's books: every book that introduces a function the host",
                 "; reaches, carries a guard verification or an attachment, and (by ACL2's",
                 "; own include-book) their non-local ancestors.  The %d excluded books are"
                 % len(excluded),
                 "; theorem-only for the running node; they stay in the certified source."]
        lines += ['(include-book "%s")' % b[:-len(".lisp")] for b in roots]
        Path(a.write).write_text("\n".join(lines) + "\n", encoding="ascii")
    return 0


if __name__ == "__main__":
    sys.exit(main())
