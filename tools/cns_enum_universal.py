#!/usr/bin/env python3
"""Emit proposed universal equalities for the actual three CNS PUT fragments.

No ACL2 is started. Reuses the admitted ground fixture's logical theory builder,
keeps the complete old/new expressions, and checks actual cached getter bindings.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tempfile
from cns_enum_controls import TABLE, TARGETS, snippets, tree, sexp
from lisp_rewrite import parse, match


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--source-root', type=Path, required=True)
    ap.add_argument('--old-ref', default='4c46607449f33dc604d944d81ea614661eba04e3')
    ap.add_argument('--new-ref', default='969065e2f')
    ap.add_argument('--emit', type=Path, required=True)
    ap.add_argument('--audit', type=Path, required=True)
    args = ap.parse_args()
    root = args.source_root.resolve()
    old = subprocess.check_output(['git', 'show', args.old_ref + ':books/cns-source-raw.lisp'], cwd=root, text=True)
    current = (root / 'books/cns-source-raw.lisp').read_text()
    new = subprocess.check_output(['git', 'show', args.new_ref + ':books/cns-source-raw.lisp'], cwd=root, text=True)
    decl = next(tree(m.node) for m in match(None, parse(root / 'books/cns-source-state.lisp'), deep=False, head='defcolumns'))
    assert decl[1] == TABLE and len(decl) == 3
    cols = decl[2]
    phase = next(i for i, c in enumerate(cols) if c[0] == 'phase')
    stage = next(i for i, c in enumerate(cols) if c[0] == 'manifest-stage')
    oldforms, newforms = snippets(old, False), snippets(new, True)
    assert snippets(current, True) == newforms, "current fragments differ from frozen runtime target"
    audit = []
    for index, name in enumerate(TARGETS):
        fn = next(m.node for m in match(None, parse(new), deep=False, head='defun') if m.node.items[1].low == name)
        body = tree(fn.items[-1])
        assert body[0] == 'b*'
        bindings = body[1]
        cached = ['phase', 'stage'] if index == 0 else ['stage'] if index == 1 else []
        positions = {}
        for field in cached:
            column = 'manifest-stage' if field == 'stage' else field
            expected = [field, [TABLE + '-' + column, 's', TABLE]]
            positions[field] = bindings.index(expected)
        writes = [i for i, b in enumerate(bindings) if b and b[0] == TABLE]
        assert len(writes) == 1 and (not positions or max(positions.values()) < writes[0])
        assert bindings[writes[0]][1] == newforms[index]
        oldfn = next(m.node for m in match(None, parse(old), deep=False, head='defun') if m.node.items[1].low == name)
        oldbody = tree(oldfn.items[-1])
        assert oldbody[0] == 'b*' and len(oldbody[1]) == len(bindings)
        assert oldbody[2:] == body[2:]
        assert all(oldbinding == newbinding for i, (oldbinding, newbinding)
                   in enumerate(zip(oldbody[1], bindings)) if i != writes[0])
        assert all(not (isinstance(b[0], list) and b[0] and b[0][0] == 'mv'
                        and TABLE in b[0]) for b in bindings[:writes[0]])
        # Direct linear carrier bindings are the continuing path: earlier
        # return/refusal arms do not flow into this final PUT expression.
        assert not any(i < writes[0] and bindings[i][0] == TABLE for i in range(len(bindings)))
        audit.append({'function': name, 'continuing_source_binding': writes[0],
                      'cached_getter_bindings': positions, 'cached_hypotheses': cached,
                      'other_body_bindings_and_return_unchanged': True,
                      'preceding_continuing_mv_outputs_exclude_sources': True,
                      'scope': 'whole returned sources carrier of the actual extracted fragment; not the complete function return/effect tuple'})

    with tempfile.TemporaryDirectory(prefix='cns-enum-universal-') as tmp:
        ground = Path(tmp) / 'ground.lisp'
        subprocess.run([sys.executable, str(Path(__file__).with_name('cns_enum_controls.py')),
                        '--source-root', str(root), '--old-ref', args.old_ref,
                        '--emit', str(ground)], check=True, capture_output=True, text=True)
        text = ground.read_text()
        definitions = list(match(None, parse(text), deep=False, head='defthm'))
        assert len(definitions) == 226
        header = text[:definitions[0].node.start]
        missing_row = text[definitions[-1].node.start:definitions[-1].node.end]
    header = header.replace('; Generated by tools/cns_enum_controls.py; ACL2 ADMISSION NOT RUN.',
                            '; Generated by tools/cns_enum_universal.py; PROPOSED UNIVERSAL EVENTS, ADMISSION NOT RUN.')
    events = [header, '''; The only new general list law. Same statement/proof pattern as the
; existing fn2-ctf-update-nth-nth-same, without importing its unrelated book.
(local (defthm fn2-cns-enum-bounded-update-self
 (implies (< (nfix i) (len xs))
          (equal (update-nth i (nth i xs) xs) xs))
 :hints (("Goal" :in-theory (enable update-nth nth)))))
''', f''' ; Actual recognizer uses LENGTH, not LEN. Derive this once from P;
; element recognizers stay opaque in the ordinary admitted theory.
(local (defthm fn2-cns-enum-actual-record-length
 (implies ({TABLE}p {TABLE}) (equal (len {TABLE}) {len(cols) + 1}))
 :rule-classes nil
 :hints (("Goal" :in-theory
  (set-difference-theories
   (enable {TABLE}p length)
   (fn2-cns-enum-stobj-execs (executable-counterpart-theory :here) world))))))
''']
    premises = f'(and ({TABLE}p {TABLE}) ({TABLE}-wfp {TABLE}) (natp s) (< s ({TABLE}-rows {TABLE})))'
    events.append(f'''(local (defthm fn2-cns-enum-actual-target-shape
 (implies {premises}
  (and (< {phase} (len {TABLE})) (< {stage} (len {TABLE}))
       (< s (len (nth {phase} {TABLE})))
       (< s (len (nth {stage} {TABLE})))) )
 :rule-classes nil
 :hints (("Goal"
  :use (fn2-cns-enum-actual-record-length
        {TABLE}-phase-length-when-wfp
        {TABLE}-manifest-stage-length-when-wfp)
  :in-theory
  (set-difference-theories
   (disable {TABLE}p {TABLE}-wfp)
   (fn2-cns-enum-stobj-execs (executable-counterpart-theory :here) world))))))
''')
    events.append('''; No TYPE/P preservation is assumed for arbitrary prefix values. The
; target shape and nth/update-nth frame equations suffice after other fields.
(local (deftheory fn2-cns-enum-universal-theory
 (set-difference-theories
  (union-theories (theory 'fn2-cns-enum-logical-theory)
   '(fn2-cns-enum-bounded-update-self
     nth-update-nth len-update-nth fn2-columns-len-update-nth))
  '((:definition nth) (:definition update-nth)
    (:definition fn2-cns-sourcesp) (:definition fn2-cns-sources-wfp)))))
''')
    for row, before, after in zip(audit, oldforms, newforms):
        hyps = [f'({TABLE}p {TABLE})', f'({TABLE}-wfp {TABLE})', '(natp s)', f'(< s ({TABLE}-rows {TABLE}))']
        for field in row['cached_hypotheses']:
            col = 'manifest-stage' if field == 'stage' else field
            hyps.append(f'(equal {field} ({TABLE}-{col} s {TABLE}))')
        name = row['function'] + '-enum-fragment-whole-carrier-equality'
        events.append(f'''(defthm {name}
 (implies (and {' '.join(hyps)})
          (equal {sexp(before)} {sexp(after)}))
 :rule-classes nil
 :hints (("Goal" :use (fn2-cns-enum-actual-target-shape)
                 :in-theory (theory 'fn2-cns-enum-universal-theory))))
''')
    events.append('; Existing actual-table missing-row negative remains unchanged.\n' + missing_row)
    result = '\n'.join(events) + '\n'
    parse(result)
    args.emit.write_text(result)
    args.audit.write_text(json.dumps({'status': 'source-only-proposed-unadmitted', 'old_ref': args.old_ref, 'new_ref': args.new_ref,
        'current_raw_sha256': hashlib.sha256(current.encode()).hexdigest(), 'current_fragments_equal_frozen_new': True,
        'raw_sha256': hashlib.sha256(new.encode()).hexdigest(), 'state_sha256': hashlib.sha256((root / 'books/cns-source-state.lisp').read_bytes()).hexdigest(),
        'fixture_sha256': hashlib.sha256(result.encode()).hexdigest(), 'phase_column': phase, 'stage_column': stage,
        'declaration_columns': len(cols), 'fragments': audit}, indent=2) + '\n')
    print(f'Emitted3 universal whole-carrier equalities + unchanged missing-row negative; cached-binding source audit passed; ACL2 not run: {args.emit}')


if __name__ == '__main__':
    main()
