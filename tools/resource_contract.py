#!/usr/bin/env python3
"""The resource contract's citations, generated so docs/resource-contract.md
cannot drift from the tree (row R1, ember 2026-09-28: "could it have a
warranty?").

    python3 tools/resource_contract.py --write    # regenerate the doc's block
    python3 tools/resource_contract.py --check    # `make check`: the block is
                                                  # current, every cited theorem
                                                  # exists, every cited proof id
                                                  # and record exists, no cited
                                                  # book is red at its digest
    python3 tools/resource_contract.py --check --strict
                                                  # the release form: also fail
                                                  # a cited book that no held
                                                  # manifest certifies at its
                                                  # current digest
    python3 tools/resource_contract.py --table    # every row's books with their
                                                  # green_check verdict and the
                                                  # registry status of its proofs
    python3 tools/resource_contract.py --json     # the same, machine-readable

WHAT IS GENERATED.  The block between the markers in docs/resource-contract.md:
one line per row naming the theorems (book and event), the proof ids and the
evidence records it rests on; the constants the rows quote, read from the
books that define them (never typed into prose); the counts (the depth lint's
baseline, the assumption rows, the encapsulates); the outcome-code table.  The
prose around the block carries the property, its hypotheses and its scope, and
must mention every row id (`--check` refuses a row the prose forgot).

WHAT IS CHECKED, and what is deliberately not.  A theorem name is checked
against its book's source (`(defthm NAME`, `defthmd`, `defkeystone`), a proof id
against planning/proofs.json, a record against the tree.  Certification is
asked of tools/green_check.py at check time, book by book, at the book's
current digest: red is a failure (the doc would cite a proof known to fail at
these bytes); `never`/`absent` is printed as UNCERTIFIED AT THIS DIGEST with
the last green run, and fails only under --strict, because between a lane's
edit and the batch's union cite a cited book is legitimately uncertified.  The
verdicts are never written into the doc: an archived manifest or an edited
book would put them out of date, as green_check says of its own table.  A
row marked `landing` names a lane whose books or theorems are not on this
tree yet: a missing book, theorem, proof id or record of such a row is
printed as PENDING, never failed, and is checked like any other once it
lands.

The rows themselves live here, in ROWS, so the doc and the tool cannot name
different theorems.
"""
