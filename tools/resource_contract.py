def lisp_int(text: str) -> int:
    """An integer literal or a `(* a b ...)` product of them, nothing else."""
    text = text.strip()
    if re.fullmatch(r"-?\d+", text):
        return int(text)
    inner = re.fullmatch(r"\(\*\s+((?:-?\d+\s*)+)\)", text)
    if inner:
        value = 1
        for factor in inner.group(1).split():
            value *= int(factor)
        return value
    raise ValueError(f"not a literal integer: {text!r}")


def constant_values(root: Path = ROOT) -> list[tuple[str, int, str, str]]:
    out = []
    for label, rel, pattern, unit in CONSTANTS:
        text = (root / rel).read_text(encoding="utf-8")
        found = re.search(pattern, text, re.M)
        if not found:
            raise SystemExit(f"resource_contract: {rel}: no definition matching {label}")
        out.append((label, lisp_int(found.group(1)), unit, rel))
    return out


def small_preset(root: Path = ROOT) -> list[tuple[str, int]]:
    text = (root / "books" / "heap-figure.lisp").read_text(encoding="utf-8")
    start = text.find("(defconst *fn-heap-small-request*")
    if start < 0:
        raise SystemExit("resource_contract: books/heap-figure.lisp: no *fn-heap-small-request*")
    block = text[start:text.find("(defconst", start + 1)]
    out = []
    for label, pattern in SMALL_PRESET:
        found = re.search(pattern, block)
        if not found:
            raise SystemExit(f"resource_contract: *fn-heap-small-request* has no {label}")
        out.append((label, int(found.group(1))))
    return out


def outcome_codes(root: Path = ROOT) -> list[tuple[str, int]]:
    text = (root / "books" / "outcome-class.lisp").read_text(encoding="utf-8")
    start = text.find("(defconst *fn-outcome-codes*")
    if start < 0:
        raise SystemExit("resource_contract: books/outcome-class.lisp: no *fn-outcome-codes*")
    block = text[start:text.find("(defconst", start + 1)]
    pairs = re.findall(r"\((:[a-z-]+) \. (\d+)\)", block)
    if not pairs:
        raise SystemExit("resource_contract: *fn-outcome-codes* has no pairs")
    return [(word, int(code)) for word, code in pairs]


def counts(root: Path = ROOT) -> dict[str, int]:
    baseline = json.loads((root / "tools" / "depth_baseline.json").read_text(encoding="utf-8"))
    failures = (root / "specs" / "failures.md").read_text(encoding="utf-8")
    assumptions = (root / "books" / "assumptions.lisp").read_text(encoding="utf-8")
    throughput = json.loads((root / "planning" / "throughput-baseline.json").read_text(encoding="utf-8"))
    return {
        "depth_debt": len(baseline.get("debt", {})),
        "depth_bounded": len(baseline.get("bounded", {})),
        "assumption_rows": len(re.findall(r"^\| A-[A-Z0-9-]+ \|", failures, re.M)),
        "encapsulates": len(re.findall(r"^\(encapsulate", assumptions, re.M)),
        "throughput_tolerance_percent": int(round(float(throughput["tolerance"]) * 100)),
    }


def theorem_defined(root: Path, book: str, name: str) -> bool | None:
    """True/False when the book exists, None when it does not."""
    path = root / f"{book}.lisp"
    if not path.is_file():
        return None
    pattern = r"^\((?:%s)\s+%s(?=[\s)])" % ("|".join(THEOREM_FORMS), re.escape(name))
    return re.search(pattern, path.read_text(encoding="utf-8"), re.M) is not None


def proof_ids(root: Path = ROOT) -> dict[str, dict]:
    data = json.loads((root / "planning" / "proofs.json").read_text(encoding="utf-8"))
    return {entry["id"]: entry for entry in data["proofs"]}


def render_block(root: Path = ROOT) -> str:
    lines = [BEGIN, "",
             "Rows, with what each cites. `landing` names a lane whose books are",
             "not on this tree yet; its citations are checked once they land.", "",
             "| Row | Theorems (book: events) | Proofs | Records | Landing |",
             "| --- | --- | --- | --- | --- |"]
    for row in ROWS:
        by_book: dict[str, list[str]] = {}
        for book, name in row.theorems:
            by_book.setdefault(book, []).append(name)
        # A name is backquoted only once the tree defines it: a backquoted
        # `fn-...` span in docs/ is a citation tools/spec_cite_check.py
        # resolves, and a landing row's names are not resolvable yet.
        def cite(book: str, name: str) -> str:
            return f"`{name}`" if theorem_defined(root, book, name) else f"{name} (pending)"
        theorems = "; ".join(f"`{book}`: " + ", ".join(cite(book, n) for n in names)
                             for book, names in by_book.items()) or "none (measured or open)"
        proofs = ", ".join(row.proofs) or "none"
        records = ", ".join(f"`{r}`" for r in row.records) or "none"
        lines.append(f"| {row.id} | {theorems} | {proofs} | {records} | {row.landing or ''} |")
    lines += ["", "Constants the rows quote, read from the books that define them.", "",
              "| Constant | Value | Meaning | Defined in |", "| --- | --- | --- | --- |"]
    for label, value, unit, rel in constant_values(root):
        lines.append(f"| `{label}` | {value:,} | {unit} | `{rel}` |")
    lines += ["", "The small preset (`*fn-heap-small-request*`, books/heap-figure.lisp);",
              "A, the article bound, is inherited from the development preset.", "",
              "| Field | Value |", "| --- | --- |"]
    for label, value in small_preset(root):
        lines.append(f"| {label} | {value:,} |")
    lines += ["", "The outcome classes and their codes (`*fn-outcome-codes*`, books/outcome-class.lisp).", "",
              "| Class | Code |", "| --- | --- |"]
    for word, code in outcome_codes(root):
        lines.append(f"| `{word}` | {code} |")
    c = counts(root)
    lines += ["", "Counts.", "",
              f"- Depth lint baseline (tools/depth_baseline.json): {c['depth_debt']} debt entries "
              f"(data-sized recursion on a host-called path with no bound), {c['depth_bounded']} bounded.",
              f"- Named assumptions: {c['assumption_rows']} `A-*` rows in specs/failures.md, "
              f"{c['encapsulates']} encapsulates in books/assumptions.lisp.",
              f"- The throughput gate's tolerance (tools/throughput_gate.py, planning/throughput-baseline.json): "
              f"{c['throughput_tolerance_percent']}% over the baseline per operation, plaintext.",
              "", END]
    return "\n".join(lines)


def splice(text: str, block: str) -> str:
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < 0:
        raise SystemExit(f"{DOC.relative_to(ROOT)}: no resource-contract region markers")
    return text[:start] + block + text[end + len(END):]


def current_block(text: str) -> str:
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < 0:
        raise SystemExit(f"{DOC.relative_to(ROOT)}: no resource-contract region markers")
    return text[start:end + len(END)]


@dataclass
class Standing:
    """One row's citations, checked against the tree."""

    row: Row
    missing_theorems: list[str] = field(default_factory=list)
    pending: list[str] = field(default_factory=list)
    missing_proofs: list[str] = field(default_factory=list)
    missing_records: list[str] = field(default_factory=list)
    proof_status: dict[str, str] = field(default_factory=dict)
    books: dict[str, dict] = field(default_factory=dict)   # green_check records


def standings(root: Path = ROOT, certification: dict | None = None) -> list[Standing]:
    proofs = proof_ids(root)
    out = []
    for row in ROWS:
        s = Standing(row)
        for book, name in row.theorems:
            defined = theorem_defined(root, book, name)
            if defined:
                continue
            what = f"{book}: {name}" + ("" if defined is False else " (book absent)")
            (s.pending if row.landing else s.missing_theorems).append(what)
        for pid in row.proofs:
            if pid in proofs:
                s.proof_status[pid] = proofs[pid]["status"]
            else:
                (s.pending if row.landing else s.missing_proofs).append(pid)
        for rel in row.records:
            if not (root / rel).exists():
                (s.pending if row.landing else s.missing_records).append(rel)
        if certification is not None:
            for book in dict.fromkeys(b for b, _ in row.theorems):
                if (root / f"{book}.lisp").is_file():
                    s.books[book] = certification.get(book, {"verdict": "absent",
                                                             "note": "not audited"})
        out.append(s)
    return out


def certification_of(root: Path, books: list[str]) -> dict:
    import green_check  # noqa: E402  (imported here: it reads every manifest)
    report = green_check.audit(root, roots=books)
    return report["books_by_verdict"]


def cited_books(root: Path = ROOT) -> list[str]:
    seen = []
    for row in ROWS:
        for book, _ in row.theorems:
            if book not in seen and (root / f"{book}.lisp").is_file():
                seen.append(book)
    return seen


def row_ids_in_prose(text: str) -> set[str]:
    prose = text[:text.find(BEGIN)] if BEGIN in text else text
    return set(re.findall(r"\*\*([MWSTCD]\d+b?)\*\*", prose))


def check(root: Path = ROOT, strict: bool = False, certify: bool = True) -> int:
    problems: list[str] = []
    notes: list[str] = []
    text = DOC.read_text(encoding="utf-8")
    if current_block(text) != render_block(root):
        problems.append(f"{DOC.relative_to(root)}: the generated block is stale; "
                        "run python3 tools/resource_contract.py --write")
    named = row_ids_in_prose(text)
    for row in ROWS:
        if row.id not in named:
            problems.append(f"row {row.id} has no prose row (write **{row.id}** in the doc)")
    for extra in sorted(named - {row.id for row in ROWS}):
        problems.append(f"the prose names row {extra}, which ROWS does not define")
    cert = certification_of(root, cited_books(root)) if certify else None
    uncertified = 0
    for s in standings(root, cert):
        for what in s.missing_theorems:
            problems.append(f"{s.row.id}: theorem not in its book: {what}")
        for pid in s.missing_proofs:
            problems.append(f"{s.row.id}: proof id not in planning/proofs.json: {pid}")
        for rel in s.missing_records:
            problems.append(f"{s.row.id}: record missing: {rel}")
        for what in s.pending:
            notes.append(f"{s.row.id}: PENDING ({s.row.landing}): {what}")
        for book, record in s.books.items():
            verdict = record["verdict"]
            if verdict == "red":
                problems.append(f"{s.row.id}: {book} is RED at its digest: {record['note']}")
            elif verdict != "green":
                uncertified += 1
                line = f"{s.row.id}: {book} UNCERTIFIED AT THIS DIGEST: {record['note']}"
                (problems if strict else notes).append(line)
    for line in notes:
        print(line)
    for line in problems:
        print(f"resource_contract: {line}", file=sys.stderr)
    verdict = "FAIL" if problems else "ok"
    print(f"resource_contract: {len(ROWS)} rows, "
          f"{sum(len(r.theorems) for r in ROWS)} cited theorems, "
          f"{len(problems)} problem(s), {uncertified} cited book(s) uncertified at this digest"
          + (" (strict)" if strict else "") + f": {verdict}")
    return 1 if problems else 0


def table(root: Path = ROOT, as_json: bool = False) -> int:
    cert = certification_of(root, cited_books(root))
    rows = standings(root, cert)
    if as_json:
        print(json.dumps([{
            "row": s.row.id, "title": s.row.title, "landing": s.row.landing,
            "proofs": s.proof_status, "pending": s.pending,
            "missing": s.missing_theorems + s.missing_proofs + s.missing_records,
            "books": {b: {"verdict": r["verdict"], "note": r["note"]}
                      for b, r in s.books.items()},
        } for s in rows], indent=1))
        return 0
    for s in rows:
        print(f"{s.row.id}  {s.row.title}")
        for pid, status in s.proof_status.items():
            print(f"      {pid}: {status}")
        for book, record in s.books.items():
            print(f"      {book}: {record['verdict']}  {record['note']}")
        for what in s.pending:
            print(f"      PENDING ({s.row.landing}): {what}")
        for what in s.missing_theorems + s.missing_proofs + s.missing_records:
            print(f"      MISSING: {what}")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--write", action="store_true", help="regenerate the doc's block")
    mode.add_argument("--check", action="store_true", help="the make check step")
    mode.add_argument("--table", action="store_true",
                      help="every row's books with their certification verdict")
    mode.add_argument("--json", action="store_true", help="--table, machine-readable")
    parser.add_argument("--strict", action="store_true",
                        help="with --check: a cited book uncertified at its digest fails")
    parser.add_argument("--no-certify", action="store_true",
                        help="with --check: skip the manifest audit (existence only)")
    args = parser.parse_args(argv)
    if args.write:
        DOC.write_text(splice(DOC.read_text(encoding="utf-8"), render_block()), encoding="utf-8")
        print(f"wrote {DOC.relative_to(ROOT)}")
        return 0
    if args.check:
        return check(strict=args.strict, certify=not args.no_certify)
    return table(as_json=args.json)


if __name__ == "__main__":
    sys.exit(main())
