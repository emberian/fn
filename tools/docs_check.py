def post_refusals():
    # The reply texts are the protocol table's (lane defprotocol-2): read the
    # book with each (fn-proto-text ROW KEY) put back as its literal, as the
    # macro expands it (tools/protocol_emit.py --expand).
    if str(Path(__file__).resolve().parent) not in sys.path:
        sys.path.insert(0, str(Path(__file__).resolve().parent))
    import protocol_emit
    text = protocol_emit.expand(protocol_emit.load(), book_text("books/nntp-post.lisp"))
    body = text[text.index("(defun fn-post-refusal-line"):]
    body = body[:body.index("\n\n")]
    return re.findall(r'\(\(equal reason :([a-z0-9-]+)\) "([^"]+)"\)', body)


def wrap(text, indent, width=72):
    """TEXT's words in lines of at most WIDTH columns, each after INDENT."""
    lines, line = [], ""
    for word in text.split():
        if line and len(indent) + len(line) + 1 + len(word) > width:
            lines.append(indent + line)
            line = word
        else:
            line = (line + " " + word) if line else word
    return lines + [indent + line]


def reasons_region():
    states, first, unobserved = health_states()
    lines = [REASONS_BEGIN, ""]
    lines += wrap("*Health codes:* health exits with the code of the first problem it "
                  "found. 0 means none; %d means the node is not running (nothing "
                  "answers on its control socket and nothing holds the store; the next "
                  "line says how its last run ended, `last-stop exit=NN reason=...`); "
                  "%d means fn could not check (the peer lines need a running node)."
                  % (health_not_running_exit(), unobserved), "")
    lines.append("")
    for index, state in enumerate(states):
        lines += wrap_item("- %d %s: " % (first + index, state),
                           HEALTH_ADVICE.get(state, "(no advice)"))
    lines.append("")
    lines += wrap("*Refusals:* A refused post is answered \"441 posting failed;\" and one "
                  "of these. The log line starts refused and names the reason.", "")
    lines.append("")
    prefix = "441 posting failed; "
    for reason, reply in post_refusals():
        tail = reply[len(prefix):] if reply.startswith(prefix) else reply
        lines += wrap_item("- %s: " % reason, tail)
    lines += ["", REASONS_END]
    return "\n".join(lines)


def wrap_item(lead, text):
    """A bullet: LEAD then TEXT, continued two spaces in, 72 columns."""
    first = wrap(lead + text, "")
    return [first[0]] + wrap(" ".join(first[1:]), "  ") if len(first) > 1 else first


def check_reasons(write):
    failures = []
    states, _first, _unobserved = health_states()
    for state in states:
        if state not in HEALTH_ADVICE:
            failures.append("health state %s (books/native-health.lisp) has no HEALTH_ADVICE "
                            "in tools/docs_check.py" % state)
    for state in HEALTH_ADVICE:
        if state not in states:
            failures.append("HEALTH_ADVICE names %s, which books/native-health.lisp no "
                            "longer has" % state)
    rel = REASONS_DOC.relative_to(ROOT).as_posix()
    text = REASONS_DOC.read_text(encoding="utf-8")
    start = text.find(REASONS_BEGIN)
    end = text.find(REASONS_END)
    if start < 0 or end < start:
        return failures + ["%s has no generated reasons region" % rel]
    region = reasons_region()
    current = text[start:end + len(REASONS_END)]
    if write:
        if current != region:
            REASONS_DOC.write_text(text[:start] + region + text[end + len(REASONS_END):],
                                   encoding="utf-8")
            print("wrote the reasons region of %s" % rel)
    elif current != region:
        failures.append("%s's reasons region is not what the books say now: "
                        "run tools/docs_check.py --write" % rel)
    return failures


# The command list of docs/articles/fn-faq-2.txt (lane defprotocol): written
# from the protocol table, books/protocol-table.lisp, through
# tools/protocol_emit.py's non-evaluating reader.  A row's :rfc and :faq are
# the text; a row with a 480 reply is marked as needing a login.
COMMANDS_DOC = ROOT / "docs" / "articles" / "fn-faq-2.txt"
COMMANDS_BEGIN = "[generated from books/protocol-table.lisp; do not edit]"
COMMANDS_END = "[end of generated text]"


def commands_region():
    sys.path.insert(0, str(ROOT / "tools"))
    import protocol_emit
    table = protocol_emit.load()
    lines = [COMMANDS_BEGIN, ""]
    lines += wrap("*Commands:* what fn answers, from its protocol table. A * "
                  "needs a login where the node requires one (480 otherwise).", "")
    lines.append("")
    for row in table["rows"]:
        if row["name"].startswith("("):
            continue
        gated = any(e["code"] == 480 for e in row["replies"])
        lead = "- %s%s (%s): " % (row["name"], " *" if gated else "", row["rfc"])
        lines += wrap_item(lead, row["faq"])
    lines += ["", COMMANDS_END]
    return "\n".join(lines)


def check_commands(write):
    rel = COMMANDS_DOC.relative_to(ROOT).as_posix()
    text = COMMANDS_DOC.read_text(encoding="utf-8")
    start = text.find(COMMANDS_BEGIN)
    end = text.find(COMMANDS_END, start + 1) if start >= 0 else -1
    region = commands_region()
    if start < 0 or end < start:
        return ["%s has no generated command region" % rel]
    current = text[start:end + len(COMMANDS_END)]
    if current == region:
        return []
    if write:
        COMMANDS_DOC.write_text(text[:start] + region + text[end + len(COMMANDS_END):],
                                encoding="utf-8")
        print("wrote the command region of %s" % rel)
        return []
    return ["%s's command region is not what books/protocol-table.lisp says now: "
            "run tools/docs_check.py --write" % rel]


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--write", action="store_true", help="regenerate the argv file")
    mode.add_argument("--check", action="store_true", help="fail on any mismatch")
    parser.add_argument("--verbose", action="store_true", help="list every invocation")
    args = parser.parse_args(argv)
    failures = check_reasons(args.write)
    failures += check_commands(args.write)
    found = inventory()
    generated = argv_file(found)
    templates = [(rel, number, line, why) for kind, rel, number, line, argv, why in found
                 if kind not in ("reply", "skip") and argv is None]
    for rel, number, line, why in templates:
        print("template %s:%d: %s -- %s" % (rel, number, line, why))
    for kind, rel, number, line, argv, why in found:
        if kind == "skip":
            print("skipped %s:%d -- %s" % (rel, number, why))
        elif args.verbose and argv is not None:
            print("%s %s:%d: %s" % (kind, rel, number, " ".join(argv)))
    if args.write:
        ARGV_FILE.write_text(generated, encoding="utf-8")
        print("wrote %s" % ARGV_FILE.relative_to(ROOT))
    elif not ARGV_FILE.exists() or ARGV_FILE.read_text(encoding="utf-8") != generated:
        failures.append("%s is not what the docs say now: run tools/docs_check.py --write "
                        "and certify it"
                        % ARGV_FILE.relative_to(ROOT))
    failures += parse_python(found)
    failures += check_replies(found)
    counts = {}
    for kind, *_ in found:
        counts[kind] = counts.get(kind, 0) + 1
    for failure in failures:
        print("FAIL " + failure)
    print("docs_check: %s; %d template(s), %d failure(s)" % (
        ", ".join("%s=%d" % kv for kv in sorted(counts.items())), len(templates), len(failures)))
    return 1 if failures and (args.check or not args.write) else 0


if __name__ == "__main__":
    sys.exit(main())
