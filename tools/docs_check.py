OPERATOR = re.compile(
    r"^(?:\$\s+)?(?:\S*/)?(?:fn|fn-native|fn-host)(?:\s+--fn)?\s+operator\s+(\S+)(?:\s+(.*))?$")
BIN_FN = re.compile(r"^(?:\$\s+)?(?:\S*/)?(?:bin/)?fn\s+(--config\s+\S+.*)$")
