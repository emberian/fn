#!/usr/bin/env python3
"""Emit a source-controlled whole-result lift of the three CNS enum fragments.

Extracts old full bodies mechanically; guards/formals/stobj declarations stay
unchanged, except proof-only clones do not attempt guard verification. The new
side is the actual served function, not a new model. Starts no ACL2/build.
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess
import sys
import tempfile
from cns_enum_controls import TABLE, TARGETS, tree, sexp
from lisp_rewrite import parse, match, write


FRAGMENT_SHA = '251861111de3bf4d8e2e4dbd4d40f68b7a9d1cf728b52fa47c1049007bb91d7c'
OPS = 'fn2-cns-source-operations'


def functions(text):
    return {m.node.items[1].low: m.node for m in match(None, parse(text), deep=False, head='defun')}


def xargs(fn):
    return next(m.node for m in match(None, [fn], deep=True, head='xargs'))


def option(node, key):
    return next(node.items[i + 1] for i, n in enumerate(node.items[:-1])
                if getattr(n, 'low', None) == key)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--source-root', type=Path, required=True)
    ap.add_argument('--old-ref', default='4c46607449f33dc604d944d81ea614661eba04e3')
    ap.add_argument('--new-ref', default='969065e2f')
    ap.add_argument('--emit', type=Path, required=True)
    ap.add_argument('--audit', type=Path, required=True)
    args = ap.parse_args()
    root = args.source_root.resolve()
    old = subprocess.check_output(['git', 'show', args.old_ref + ':books/cns-source-raw.lisp'], cwd=root, text=True)
    new = subprocess.check_output(['git', 'show', args.new_ref + ':books/cns-source-raw.lisp'], cwd=root, text=True)
    current = (root / 'books/cns-source-raw.lisp').read_text()
    olds, news, currents = functions(old), functions(new), functions(current)
    fragment = Path(__file__).resolve().parent.parent / 'tests/cns-enum-universal-controls.lisp'
    assert hashlib.sha256(fragment.read_bytes()).hexdigest() == FRAGMENT_SHA
    formulas = {m.node.items[1].low: m.node.items[2] for m in match(None, parse(fragment), deep=False, head='defthm')}
    with tempfile.TemporaryDirectory(prefix='cns-enum-whole-lift-') as tmp:
        universal, audit = Path(tmp) / 'universal.lisp', Path(tmp) / 'audit.json'
        subprocess.run([sys.executable, str(Path(__file__).with_name('cns_enum_universal.py')),
                        '--source-root', str(root), '--old-ref', args.old_ref, '--new-ref', args.new_ref,
                        '--emit', str(universal), '--audit', str(audit)], check=True, capture_output=True, text=True)
        assert hashlib.sha256(universal.read_bytes()).hexdigest() == FRAGMENT_SHA
        prefix_audit = json.loads(audit.read_text())
    events = ['; Generated by tools/cns_enum_whole_lift.py; WHOLE LIFT UNADMITTED.',
              '(in-package "ACL2")', '(include-book "../books/cns-source-raw")',
              '(include-book "cns-enum-universal-controls")', '''; This follows the actual owner predicate, without opening field getters.
(local (defthm fn2-cns-enum-owner-implies-valid-row
 (implies (fn2-cns-source-ownerp s cns cnsgen ctl ctlgen request fn2-cns-sources)
          (and (natp s) (< s (fn2-cns-sources-rows fn2-cns-sources))))
 :rule-classes :forward-chaining
 :hints (("Goal" :in-theory
  (union-theories '((:definition fn2-cns-source-ownerp))
                  (theory 'minimal-theory))))))''']
    rows = []
    for index, name in enumerate(TARGETS):
        oldfn, newfn, currentfn = olds[name], news[name], currents[name]
        formals = tree(oldfn.items[2])
        assert tree(newfn.items[2]) == tree(currentfn.items[2]) == formals
        assert tree(newfn.items[-1]) == tree(currentfn.items[-1])
        oldxa, newxa, curxa = xargs(oldfn), xargs(newfn), xargs(currentfn)
        assert tree(option(oldxa, ':guard')) == tree(option(newxa, ':guard')) == tree(option(curxa, ':guard'))
        stobjs = tree(option(oldxa, ':stobjs'))
        assert stobjs == tree(option(newxa, ':stobjs')) == tree(option(curxa, ':stobjs'))
        assert name not in [m.node.items[0].low for m in match(None, [oldfn.items[-1]], deep=True, head=name)]
        clone = name + '-enum-frozen-old'
        # Only the new name and proof-only verification setting are edited.
        assert not any(getattr(n, 'low', None) == ':verify-guards' for n in oldxa.items)
        text = write(old, [(oldfn.items[1].start, oldfn.items[1].end, clone),
                           (oldxa.end - 1, oldxa.end - 1, ' :verify-guards nil')])
        clonefn = functions(text)[clone]
        clone_text = text[clonefn.start:clonefn.end]
        assert tree(clonefn.items[2]) == formals and tree(clonefn.items[-1]) == tree(oldfn.items[-1])
        assert tree(option(xargs(clonefn), ':guard')) == tree(option(oldxa, ':guard'))
        assert tree(option(xargs(clonefn), ':stobjs')) == stobjs
        events.append('; Mechanically extracted frozen OLD function; guards unchanged.\n' + clone_text)
        original = name + '-enum-fragment-whole-carrier-equality'
        alias = name + '-enum-fragment-rewrite-in-context'
        formula = formulas[original]
        fragment_text = fragment.read_text()[formula.start:formula.end]
        events.append(f'''(local (defthm {alias}
 {fragment_text}
 :rule-classes :rewrite
 :hints (("Goal" :by {original}))))''')
        hyps = [f'({TABLE}p {TABLE})', f'({TABLE}-wfp {TABLE})']
        if index == 1:
            hyps += [f'({OPS}p {OPS})', f'({OPS}-wfp {OPS})']
        rules = [f'(:definition {clone})', f'(:definition {name})', alias,
                 'fn2-cns-enum-owner-implies-valid-row',
                 'car-cons', 'cdr-cons', '(:e equal)', '(:e not)']
        if index == 1:
            rules.append('(:type-prescription fn2-cns-source-operations-source-row-natp)')
        law = name + '-enum-old-new-whole-result-equality'
        events.append(f'''(defthm {law}
 (implies (and {' '.join(hyps)})
          (equal ({clone} {' '.join(formals)})
                 ({name} {' '.join(formals)})))
 :rule-classes nil
 :hints (("Goal" :in-theory
  (union-theories '({' '.join(rules)}) (theory 'minimal-theory)))))''')
        row = prefix_audit['fragments'][index]
        body = tree(newfn.items[-1])
        assert body[0] == 'b*' and body[-1][0] == 'mv'
        row.update({'old_clone': clone, 'whole_theorem': law, 'formal_arguments': formals,
                    'stobjs': stobjs, 'continuing_result_tuple': body[-1],
                    'old_source_guard_preserved': True, 'current_guard_formals_body_equal_frozen_new': True,
                    'clone_body_sha256': hashlib.sha256(old[oldfn.items[-1].start:oldfn.items[-1].end].encode()).hexdigest(),
                    'current_body_sha256': hashlib.sha256(current[currentfn.items[-1].start:currentfn.items[-1].end].encode()).hexdigest(),
                    'input_hypotheses': hyps,
                    'row_discharge': 'Actual input operations P/WFP and checked op bounds imply NATP source-row via public typed getter; source-row bound is the actual continuing guard' if index == 1 else 'Actual owner predicate implies NATP row and row < ROWS on continuing branch',
                    'effects_scope': 'Complete ACL2 MV return including every returned carrier and scalar; not native host/I/O effect correspondence'})
        rows.append(row)
    result = '\n\n'.join(events) + '\n'
    parse(result)
    args.emit.write_text(result)
    args.audit.write_text(json.dumps({'status': 'source-only-whole-lift-unadmitted',
        'old_ref': args.old_ref, 'new_ref': args.new_ref, 'current_raw_sha256': hashlib.sha256(current.encode()).hexdigest(),
        'fragment_book_sha256': FRAGMENT_SHA, 'whole_fixture_sha256': hashlib.sha256(result.encode()).hexdigest(),
        'dependency_policy': 'Actual qualified RAW book and qualified universal fragment book; do not replay an author-only RAW prefix or passing fragments',
        'fragments': rows}, indent=2) + '\n')
    print(f'Emitted3 actual whole-MV equality proposals, 3 mechanically extracted old clones and exact local fragment rewrite aliases; source audit passed; ACL2 not run: {args.emit}')


if __name__ == '__main__':
    main()
