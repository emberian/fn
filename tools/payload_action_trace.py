#!/usr/bin/env python3
"""Closed action-source observers. Borrow effects are reproduced, not priced.

Includes actual bomb/copy traces; other getter/setter/bit helpers remain
explicit borrowed operations, so this is not a full transitive runtime tax.
"""
from pathlib import Path
import argparse
import hashlib
from ledger import Sym, read_forms
from payload_profile_trace import Instrument, sexp

ROOT = Path(__file__).resolve().parents[1]
SOURCE = 'books/deflate-inflate.lisp'
SELECTED = ('fn-zin-emit', 'fn-zin-pull', 'fn-zin-match')
BORROWED = frozenset(('zp', 'fn-zin-wpos', 'fn-zin-n', 'fn-zin-dist',
    'fn-zin-preset', 'fn-zin-set', 'fn-zin-wrap', 'fn-zin-out-append-octet',
    'fn-zin-win-put', 'fn-octets-get', 'fn-zin-shift-in', 'fn-zin-bits',
    'fn-zin-nbits'))

class ActionInstrument(Instrument):
    def expr(self, x):
        if isinstance(x, list) and x:
            op, *args = x
            op = str(op).lower()
            if op == 'mv-let':
                if len(args) != 3 or not isinstance(args[0], list):
                    raise ValueError('unreviewed mv-let shape')
                names, call, body = args
                value, result = self.fresh(), self.fresh()
                bindings = ' '.join(f'({sexp(n)} (mv-nth {i} (car {value})))'
                                    for i, n in enumerate(names))
                return (f'(let (({value} {self.expr(call)})) '
                        f'(let ({bindings}) (let (({result} {self.expr(body)})) '
                        f'(cons (car {result}) (append (cdr {value}) (cdr {result}))))))')
            if op in BORROWED:
                def done(values, traces):
                    site = self.fresh()
                    call = f'({op} {" ".join(values)})'
                    event = f'(list (list :borrow \'{op} \'{site}))'
                    return f'(cons {call} {self.combine(traces + [event])})'
                return self.bind(args, done)
        return super().expr(x)

def generate():
    path = ROOT / SOURCE
    definitions = {str(f[1]).lower(): f for f in read_forms(path.read_text())
                   if isinstance(f, list) and f and str(f[0]).lower() == 'defun'}
    names = {n: 'fn-pat-' + n.removeprefix('fn-') for n in SELECTED}
    names.update({'fn-zin-bomb-limit': 'fn-pzt-zin-bomb-limit',
                  'fn-zin-copy': 'fn-pzc-copy'})
    gen = ActionInstrument(names)
    out = ['; GENERATED by tools/payload_action_trace.py. Source, not allocator lowering.',
           '; '+SOURCE+' SHA256 '+hashlib.sha256(path.read_bytes()).hexdigest(),
           '(in-package "ACL2")', '(include-book "payload-copy-source-trace")']
    for original in SELECTED:
        form = definitions[original]; name = names[original]
        params = sexp(form[2]); args = ' '.join(map(sexp, form[2]))
        out += [f'(defun-nx {name} {params}\n {gen.expr(form[-1])})',
                f'(defthm {name}-value-and-effects-projection\n'
                f' (equal (car ({name} {args})) ({original} {args}))\n'
                f' :hints (("Goal" :do-not \'(preprocess)\n'
                f'   :in-theory (e/d ({name} {original})\n'
                f'      (fn-pzc-copy fn-zin-copy fn-zin-set fn-zin-wrap\n'
                f'       fn-zin-out-append-octet fn-zin-win-put fn-zin-shift-in\n'
                f'       fn-octets-get fn-zin-fld binary-append)))))',
                f'(in-theory (disable {name}))']
    return '\n\n'.join(out)+'\n'

if __name__ == '__main__':
    p = argparse.ArgumentParser();p.add_argument('--write',action='store_true')
    p.add_argument('--check',action='store_true'); a=p.parse_args();out=generate()
    target=ROOT/'books/payload-action-source-trace.lisp'
    if a.write:target.write_text(out)
    elif a.check:
        if not target.exists() or target.read_text()!=out:
            raise SystemExit('payload action source observer is stale')
        print('payload action source observer matches trusted source')
    else:print(out,end='')
