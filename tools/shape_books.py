#!/usr/bin/env python3
"""Which books are SHAPE books: the ones whose change recertifies the most.

    python3 tools/shape_books.py                # the top 40, with counts and last change
    python3 tools/shape_books.py --top 100
    python3 tools/shape_books.py --book books/held-record.lisp
    python3 tools/shape_books.py --json
    python3 tools/shape_books.py --write-doc    # regenerate docs/proof-style.md's table
    python3 tools/shape_books.py --check        # warn (exit 0) when that table is stale
    python3 tools/shape_books.py --critical     # the longest include chain in the tree
    python3 tools/shape_books.py --critical --affected-by books/config.lisp
                                                # ... among what a change to config recertifies
    python3 tools/shape_books.py --chain books/owner.lisp   # the longest chain through owner

THE CHAIN.  A recertification's wall time is its longest include chain, not
its size over the core count (planning/architecture-recommendation-
2026-09-28.md section 4.2: 509 s wall against a 466 s chain, 656 against 642,
385 against 384).  `--critical` prints that chain, top down, each book with
its predicted quiet seconds (tools/chain_schedule.py: its last archived wall
over the slowdown at the load it ran under), and what `--jobs auto` would
predict on each box.  The "books under 10 s" ratchet pays most on these books.

Lane served-columns spent an hour choosing where a column lives (arena vs
facts vs a new stobj) because nothing said that books/held-record.lisp is
included, transitively, by about a thousand books: changing it recertifies
all of them.  This prints that cost before the choice.

THE GRAPH is the farm's: `tools/certify_books.py`'s `local_closure` over the
Makefile's roots (`default_books`), the one `--affected-by` walks when
tools/farm.py selects what to recertify.  No second reading of include-book
lives here.  A certificate is content-hashed over its book and everything it
includes, so a change to book B invalidates B and every book that includes B
transitively.  For each book this prints

  dependents  the books that recertify when it changes (itself included),
  roots       how many of those are Makefile roots (what `--affected-by`
              selects; the farm certifies their closures),
  changed     the date of the last commit touching the file (`git log -1`),
              or "unknown" in a tree without .git (an rsynced box tree).

WHY --check WARNS AND DOES NOT FAIL.  The counts move with every include a
lane adds anywhere in the tree; a failing check would make every such lane
regenerate a doc table it did not mean to touch, and the table is guidance
for choosing, not a claim anything rests on.  `make check` prints the drift.
"""
from __future__ import annotations

import argparse
import collections
import json
import os
from pathlib import Path
import subprocess
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import certify_books  # noqa: E402
import chain_schedule  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "proof-style.md"
BEGIN = "<!-- BEGIN shape-books: generated by tools/shape_books.py --write-doc; do not edit -->"
END = "<!-- END shape-books -->"
DOC_TOP = 40


def fan_in(closure: dict[str, list[str]], roots: list[str]) -> dict[str, tuple[int, int]]:
    """book -> (dependents including itself, roots among them), over CLOSURE
    (book -> the books it includes)."""
    included_by: dict[str, set[str]] = collections.defaultdict(set)
    for book, includes in closure.items():
        for dependency in includes:
            included_by[dependency].add(book)
    root_set = set(roots)
    counts: dict[str, tuple[int, int]] = {}
    for book in closure:
        seen = {book}
        stack = [book]
        while stack:
            for parent in included_by.get(stack.pop(), ()):
                if parent not in seen:
                    seen.add(parent)
                    stack.append(parent)
        counts[book] = (len(seen), len(seen & root_set))
    return counts


def ranked(counts: dict[str, tuple[int, int]]) -> list[tuple[str, int, int]]:
    return sorted(((book, d, r) for book, (d, r) in counts.items()),
                  key=lambda row: (-row[1], -row[2], row[0]))


def last_changed(book: str, root: Path = ROOT) -> str:
    if not (root / ".git").exists():
        return "unknown"
    try:
        result = subprocess.run(["git", "log", "-1", "--format=%cs %h", "--", f"{book}.lisp"],
                                cwd=root, capture_output=True, text=True, timeout=60)
    except (OSError, subprocess.TimeoutExpired):
        return "unknown"
    return result.stdout.strip() or "unknown"


def tree_counts() -> tuple[dict[str, tuple[int, int]], int]:
    roots = certify_books.default_books()
    closure = certify_books.local_closure(roots)
    return fan_in(closure, roots), len(roots)


def table(rows: list[tuple[str, int, int]], total: int, roots: int,
          dates: bool = True) -> list[str]:
    lines = [f"| book | dependents (of {total}) | roots (of {roots}) |"
             + (" last changed |" if dates else ""),
             "|---|---:|---:|" + ("---|" if dates else "")]
    for book, dependents, affected in rows:
        lines.append(f"| `{book}.lisp` | {dependents} | {affected} |"
                     + (f" {last_changed(book)} |" if dates else ""))
    return lines


def doc_region(counts: dict[str, tuple[int, int]], roots: int) -> str:
    # No dates in the doc: they would make the region stale on every commit.
    body = table(ranked(counts)[:DOC_TOP], len(counts), roots, dates=False)
    return "\n".join([BEGIN, "", *body, "", END])


def replace_region(text: str, region: str) -> str:
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < start:
        raise SystemExit(f"{DOC.relative_to(ROOT)}: no shape-books region markers")
    return text[:start] + region + text[end + len(END):]


def dependents_set(closure: dict[str, list[str]], targets: list[str]) -> set[str]:
    """Every book of CLOSURE that is, or transitively includes, a target."""
    included_by: dict[str, set[str]] = collections.defaultdict(set)
    for book, includes in closure.items():
        for dependency in includes:
            included_by[dependency].add(book)
    seen = set(targets)
    stack = list(targets)
    while stack:
        for parent in included_by.get(stack.pop(), ()):
            if parent not in seen:
                seen.add(parent)
                stack.append(parent)
    return seen


SEARCH_DIRS = ("books", "tests/acl2", "host")


def resolve_book(word: str, root: Path = ROOT) -> str:
    """A book word as a repository-relative book name, the way farm takes it.

    `books/wire`, `books/wire.lisp` and an absolute path name themselves (as
    farm and certify_books take them); a bare `wire` is looked up under
    books/, tests/acl2/ and host/ and must name exactly one.  Two lanes lost
    time to `--book bp-fnbs-codec` dying in a ValueError traceback
    (2026-09-29); the refusal now names what was tried.
    """
    path = Path(word)
    if path.is_absolute():
        resolved = path.resolve()
        if not resolved.is_relative_to(root.resolve()):
            raise SystemExit(f"shape_books: {word}: outside the repository {root}")
        path = resolved.relative_to(root.resolve())
    text = path.as_posix()
    name = text[:-len(".lisp")] if text.endswith(".lisp") else text
    if (root / f"{name}.lisp").is_file():
        return name
    if "/" not in name:
        found = [f"{d}/{name}" for d in SEARCH_DIRS if (root / d / f"{name}.lisp").is_file()]
        if len(found) == 1:
            return found[0]
        if found:
            raise SystemExit(f"shape_books: {word}: ambiguous, name one of "
                             + ", ".join(f + ".lisp" for f in found))
    tried = [f"{name}.lisp"] + ([f"{d}/{name}.lisp" for d in SEARCH_DIRS] if "/" not in name else [])
    raise SystemExit(f"shape_books: {word}: no such book (tried {', '.join(tried)})")


def chain_report(affected_by: list[str] = (), through: str | None = None,
                 closure: dict[str, list[str]] | None = None,
                 boxes: tuple[str, ...] = ("persvati", "hbox"),
                 limit: int | None = None) -> list[str]:
    """The critical-chain report: the set, the chain top down, the plans.

    The set is the tree (the Makefile roots' closure), or with AFFECTED_BY
    the books a change to those recertifies (what an incremental farm run
    certifies when the cache holds the rest)."""
    if closure is None:
        closure = certify_books.local_closure(certify_books.default_books())
    targets = [resolve_book(book) for book in affected_by]
    for book in targets + ([through] if through else []):
        if book not in closure:
            raise SystemExit(f"shape_books: {book}: not in the Makefile roots' closure")
    members = dependents_set(closure, targets) if targets else set(closure)
    books = [book for book in chain_schedule.topological(
        sorted(closure), {b: set(closure[b]) & closure.keys() for b in closure}) if book in members]
    graph = {book: {d for d in closure[book] if d in members} for book in books}
    walls = chain_schedule.quiet_walls(books, host=boxes[0])
    chain = chain_schedule.critical_chain(books, graph, walls.seconds, through)
    total = sum(walls.seconds[book] for book in chain)
    work = sum(walls.seconds.values())
    scope = ("the tree" if not targets else
             "what " + ", ".join(t + ".lisp" for t in targets) + " recertifies")
    lines = [f"{scope}: {len(books)} books, {work:.0f} s quiet work; "
             f"{walls.measured} measured, the rest count the median {walls.fill:.1f} s",
             f"critical chain{' through ' + through + '.lisp' if through else ''}: "
             f"{len(chain)} books, {total:.0f} s quiet on {boxes[0]} "
             f"(top down, predicted quiet seconds):"]
    shown = chain if limit is None or len(chain) <= limit else chain[-limit:]
    lines += ["  " + line for line in chain_schedule.chain_lines(shown, walls.seconds)]
    if shown is not chain:
        lines.append(f"  ... and {len(chain) - len(shown)} more below")
    for box in boxes:
        on_box = walls if box == boxes[0] else chain_schedule.quiet_walls(books, host=box)
        plan = chain_schedule.choose_jobs(books, graph, on_box.seconds,
                                          chain_schedule.DEFAULT_CEILING, 24, 0.0, box)
        at = {j: plan.predicted_by_jobs[j] for j in (4, 8, 12, 16) if j in plan.predicted_by_jobs}
        lines.append(f"  {box} (quiet, 24 CPUs): --jobs auto -> {plan.jobs} jobs, "
                     f"predicted {plan.predicted_seconds:.0f} s; "
                     + ", ".join(f"{s:.0f} s at {j}" for j, s in at.items()))
    return lines


REEXEC_MARK = "FN_SHAPE_BOOKS_TREE"


def fn_tree(start: Path) -> Path | None:
    """The fn tree (a directory with tools/shape_books.py and a Makefile)
    containing START, walking up; None outside every one."""
    start = start.resolve()
    for candidate in (start, *start.parents):
        if (candidate / "tools" / "shape_books.py").is_file() and (candidate / "Makefile").is_file():
            return candidate
    return None


def own_tree(argv: list[str], cwd: Path, root: Path = ROOT) -> Path | None:
    """The tree whose own graph answers ARGV, when it is not ROOT's.

    `python3 ~/dev/fn/tools/shape_books.py --book X` run from a lane worktree
    read the MAIN checkout's Makefile and sources: a book new on the branch
    was "not in the closure", an absolute path into the worktree "outside
    the repository", and a moved include gave main's count (composed-owner-6
    and store-lineage, 2026-09-29).  The answer belongs to the branch: an
    absolute book path inside another fn tree names that tree, else the
    tree the shell stands in.  None when that is ROOT itself.
    """
    words = iter(argv)
    for word in words:
        value = None
        if word in ("--book", "--affected-by", "--chain"):
            value = next(words, None)
        elif word.startswith(("--book=", "--affected-by=", "--chain=")):
            value = word.split("=", 1)[1]
        if value and Path(value).is_absolute():
            tree = fn_tree(Path(value).parent)
            if tree is not None:
                return None if tree == root.resolve() else tree
    tree = fn_tree(cwd)
    return None if tree is None or tree == root.resolve() else tree


def main(argv: list[str] | None = None) -> int:
    argv = list(sys.argv[1:] if argv is None else argv)
    if not os.environ.get(REEXEC_MARK):
        tree = own_tree(argv, Path.cwd())
        if tree is not None:
            print(f"shape_books: answering from {tree} (the tree this names), "
                  f"not {ROOT}", file=sys.stderr, flush=True)
            os.environ[REEXEC_MARK] = str(tree)
            os.execv(sys.executable, [sys.executable, str(tree / "tools" / "shape_books.py"),
                                      *argv])
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--top", type=int, default=40)
    parser.add_argument("--book", action="append", default=[],
                        help="print this book's counts (repeatable; with or without .lisp)")
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--write-doc", action="store_true",
                        help="regenerate the table in docs/proof-style.md")
    parser.add_argument("--check", action="store_true",
                        help="warn (exit 0) when docs/proof-style.md's table is stale")
    parser.add_argument("--critical", action="store_true",
                        help="print the longest include chain (of the tree, or with "
                             "--affected-by of what that change recertifies)")
    parser.add_argument("--chain", metavar="BOOK",
                        help="print the longest include chain through BOOK")
    parser.add_argument("--affected-by", action="append", default=[], metavar="BOOK",
                        help="the critical-chain view restricted to the books this "
                             "change recertifies (repeatable; implies --critical "
                             "unless --chain is given)")
    arguments = parser.parse_args(argv)

    if arguments.affected_by and (arguments.book or arguments.write_doc or arguments.check):
        parser.error("--affected-by is the critical-chain view; it does not combine with "
                     "--book, --write-doc or --check")
    if arguments.critical or arguments.chain or arguments.affected_by:
        # --affected-by alone used to fall through to the top table, the
        # restriction silently dropped (assurance-hygiene, 2026-09-29).
        through = resolve_book(arguments.chain) if arguments.chain else None
        print("\n".join(chain_report(arguments.affected_by, through)))
        return 0
    counts, roots = tree_counts()
    if arguments.write_doc or arguments.check:
        text = DOC.read_text(encoding="utf-8")
        fresh = replace_region(text, doc_region(counts, roots))
        if arguments.write_doc:
            DOC.write_text(fresh, encoding="utf-8")
            print(f"shape_books: wrote the top {DOC_TOP} to {DOC.relative_to(ROOT)}")
        elif fresh != text:
            print(f"shape_books: WARN {DOC.relative_to(ROOT)}'s shape-books table is stale; "
                  "regenerate with `python3 tools/shape_books.py --write-doc` (a warning, "
                  "not a failure: the counts move with every include)")
        else:
            print("shape_books: docs/proof-style.md's table is current")
        return 0
    if arguments.book:
        rows = []
        for name in arguments.book:
            book = resolve_book(name)
            if book not in counts:
                print(f"shape_books: {name}: not in the Makefile roots' closure", file=sys.stderr)
                return 2
            rows.append((book, *counts[book]))
    else:
        rows = ranked(counts)[:arguments.top]
    if arguments.json:
        print(json.dumps({"books": len(counts), "roots": roots, "rows": [
            {"book": f"{b}.lisp", "dependents": d, "roots": r, "changed": last_changed(b)}
            for b, d, r in rows]}, indent=2))
        return 0
    print("\n".join(table(rows, len(counts), roots)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
