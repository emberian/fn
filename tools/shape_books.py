#!/usr/bin/env python3
"""Which books are SHAPE books: the ones whose change recertifies the most.

    python3 tools/shape_books.py                # the top 40, with counts and last change
    python3 tools/shape_books.py --top 100
    python3 tools/shape_books.py --book books/held-record.lisp
    python3 tools/shape_books.py --json
    python3 tools/shape_books.py --write-doc    # regenerate docs/proof-style.md's table
    python3 tools/shape_books.py --check        # warn (exit 0) when that table is stale
    python3 tools/shape_books.py --chain --book books/wildmat.lisp   # with chain position

Lane served-columns spent an hour choosing where a column lives (arena vs
facts vs a new stobj) because nothing said that books/held-record.lisp is
included, transitively, by about a thousand books: changing it recertifies
all of them.  This prints that cost before the choice.

THE GRAPH is the farm's: `tools/certify_books.py`'s `local_closure` over the
Makefile's roots (`default_books`), the one `--affected-by` walks when
tools/farm.py selects what to recertify.  No second reading of include-book
lives here.  A certificate is content-hashed over its book and everything it
includes, so a change to book B invalidates B and every book that includes B
transitively.  For each book this prints

  dependents  the books that recertify when it changes (itself included),
  roots       how many of those are Makefile roots (what `--affected-by`
              selects; the farm certifies their closures),
  changed     the date of the last commit touching the file (`git log -1`),
              or "unknown" in a tree without .git (an rsynced box tree).

CHAIN POSITION (`--chain`).  A recertification's wall time is its longest
include chain, not its size (planning/architecture-recommendation-2026-09-28.md
section 4.2: three runs, three matches).  `--chain` adds, per book, `below`
(the longest include chain ending at it, itself counted), `above` (the longest
chain of includers over it, itself counted) and `through` (below + above - 1,
the longest chain that passes through it), and prints the graph's depth.  A
fan-in cut that lowers `through` for books on the longest chain shortens
every run that reaches them; one that only lowers `dependents` saves work.

WHY --check WARNS AND DOES NOT FAIL.  The counts move with every include a
lane adds anywhere in the tree; a failing check would make every such lane
regenerate a doc table it did not mean to touch, and the table is guidance
for choosing, not a claim anything rests on.  `make check` prints the drift.
"""
from __future__ import annotations

import argparse
import collections
import json
from pathlib import Path
import subprocess
import sys

sys.path.insert(0, str(Path(__file__).resolve().parent))
import certify_books  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
DOC = ROOT / "docs" / "proof-style.md"
BEGIN = "<!-- BEGIN shape-books: generated by tools/shape_books.py --write-doc; do not edit -->"
END = "<!-- END shape-books -->"
DOC_TOP = 40


def fan_in(closure: dict[str, list[str]], roots: list[str]) -> dict[str, tuple[int, int]]:
    """book -> (dependents including itself, roots among them), over CLOSURE
    (book -> the books it includes)."""
    included_by: dict[str, set[str]] = collections.defaultdict(set)
    for book, includes in closure.items():
        for dependency in includes:
            included_by[dependency].add(book)
    root_set = set(roots)
    counts: dict[str, tuple[int, int]] = {}
    for book in closure:
        seen = {book}
        stack = [book]
        while stack:
            for parent in included_by.get(stack.pop(), ()):
                if parent not in seen:
                    seen.add(parent)
                    stack.append(parent)
        counts[book] = (len(seen), len(seen & root_set))
    return counts


def chain_position(closure: dict[str, list[str]]) -> dict[str, tuple[int, int]]:
    """book -> (below, above): the longest include chain ending at the book and
    the longest includer chain starting at it, each counting the book."""
    included_by: dict[str, set[str]] = collections.defaultdict(set)
    for book, includes in closure.items():
        for dependency in includes:
            included_by[dependency].add(book)
    below: dict[str, int] = {}
    above: dict[str, int] = {}

    def depth(book: str, edges, memo: dict[str, int]) -> int:
        # Iterative: the graph is ~65 deep, but a recursive walk would still
        # couple this tool to Python's recursion limit.
        stack = [book]
        while stack:
            top = stack[-1]
            if top in memo:
                stack.pop()
                continue
            pending = [n for n in edges(top) if n not in memo]
            if pending:
                stack.extend(pending)
                continue
            memo[top] = 1 + max((memo[n] for n in edges(top)), default=0)
            stack.pop()
        return memo[book]

    for book in closure:
        depth(book, lambda b: closure.get(b, ()), below)
        depth(book, lambda b: included_by.get(b, ()), above)
    return {book: (below[book], above[book]) for book in closure}


def ranked(counts: dict[str, tuple[int, int]]) -> list[tuple[str, int, int]]:
    return sorted(((book, d, r) for book, (d, r) in counts.items()),
                  key=lambda row: (-row[1], -row[2], row[0]))


def last_changed(book: str, root: Path = ROOT) -> str:
    if not (root / ".git").exists():
        return "unknown"
    try:
        result = subprocess.run(["git", "log", "-1", "--format=%cs %h", "--", f"{book}.lisp"],
                                cwd=root, capture_output=True, text=True, timeout=60)
    except (OSError, subprocess.TimeoutExpired):
        return "unknown"
    return result.stdout.strip() or "unknown"


def tree_counts() -> tuple[dict[str, tuple[int, int]], int]:
    roots = certify_books.default_books()
    closure = certify_books.local_closure(roots)
    return fan_in(closure, roots), len(roots)


def table(rows: list[tuple[str, int, int]], total: int, roots: int,
          dates: bool = True) -> list[str]:
    lines = [f"| book | dependents (of {total}) | roots (of {roots}) |"
             + (" last changed |" if dates else ""),
             "|---|---:|---:|" + ("---|" if dates else "")]
    for book, dependents, affected in rows:
        lines.append(f"| `{book}.lisp` | {dependents} | {affected} |"
                     + (f" {last_changed(book)} |" if dates else ""))
    return lines


def doc_region(counts: dict[str, tuple[int, int]], roots: int) -> str:
    # No dates in the doc: they would make the region stale on every commit.
    body = table(ranked(counts)[:DOC_TOP], len(counts), roots, dates=False)
    return "\n".join([BEGIN, "", *body, "", END])


def replace_region(text: str, region: str) -> str:
    start, end = text.find(BEGIN), text.find(END)
    if start < 0 or end < start:
        raise SystemExit(f"{DOC.relative_to(ROOT)}: no shape-books region markers")
    return text[:start] + region + text[end + len(END):]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--top", type=int, default=40)
    parser.add_argument("--book", action="append", default=[],
                        help="print this book's counts (repeatable; with or without .lisp)")
    parser.add_argument("--json", action="store_true")
    parser.add_argument("--chain", action="store_true",
                        help="add each book's chain position (below, above, through)")
    parser.add_argument("--write-doc", action="store_true",
                        help="regenerate the table in docs/proof-style.md")
    parser.add_argument("--check", action="store_true",
                        help="warn (exit 0) when docs/proof-style.md's table is stale")
    arguments = parser.parse_args(argv)

    counts, roots = tree_counts()
    if arguments.write_doc or arguments.check:
        text = DOC.read_text(encoding="utf-8")
        fresh = replace_region(text, doc_region(counts, roots))
        if arguments.write_doc:
            DOC.write_text(fresh, encoding="utf-8")
            print(f"shape_books: wrote the top {DOC_TOP} to {DOC.relative_to(ROOT)}")
        elif fresh != text:
            print(f"shape_books: WARN {DOC.relative_to(ROOT)}'s shape-books table is stale; "
                  "regenerate with `python3 tools/shape_books.py --write-doc` (a warning, "
                  "not a failure: the counts move with every include)")
        else:
            print("shape_books: docs/proof-style.md's table is current")
        return 0
    if arguments.book:
        rows = []
        for name in arguments.book:
            book = certify_books.normalize_book(name)
            if book not in counts:
                print(f"shape_books: {name}: not in the Makefile roots' closure", file=sys.stderr)
                return 2
            rows.append((book, *counts[book]))
    else:
        rows = ranked(counts)[:arguments.top]
    if arguments.chain:
        position = chain_position(certify_books.local_closure(certify_books.default_books()))
        depth = max(below for below, _ in position.values())
        if arguments.json:
            print(json.dumps({"books": len(counts), "roots": roots, "depth": depth, "rows": [
                {"book": f"{b}.lisp", "dependents": d, "roots": r,
                 "below": position[b][0], "above": position[b][1],
                 "through": sum(position[b]) - 1} for b, d, r in rows]}, indent=2))
            return 0
        print(f"graph depth (longest include chain): {depth}")
        print(f"| book | dependents (of {len(counts)}) | roots (of {roots}) | below | above | through |")
        print("|---|---:|---:|---:|---:|---:|")
        for b, d, r in rows:
            print(f"| `{b}.lisp` | {d} | {r} | {position[b][0]} | {position[b][1]} | "
                  f"{sum(position[b]) - 1} |")
        return 0
    if arguments.json:
        print(json.dumps({"books": len(counts), "roots": roots, "rows": [
            {"book": f"{b}.lisp", "dependents": d, "roots": r, "changed": last_changed(b)}
            for b, d, r in rows]}, indent=2))
        return 0
    print("\n".join(table(rows, len(counts), roots)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
